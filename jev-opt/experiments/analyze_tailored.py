"""Validation-only analysis of the jev-tailored dev study (Jev-adapted GEPA) -> results/GEPA_tailored_val.md.

Reads each run's `val_predictions.json`, recomputes the primary metric and reports a 95% percentile bootstrap
CI over val examples (2,000 resamples, seed 0) plus paired bootstrap differences (same resamples) of the
tailored rows to their comparison rows: the paper seed as written / fitted inside the same run, v2-A (paper
seed + class bias), the v2 best configuration, the v3 chosen configuration (third pre-registration's rule) and v3 A (paper
seed + readout head). v1 text/program-opt rows are point values from their `pareto.json` (v1 runs predate
`val_predictions.json`). Costs: Jev fresh = spend billed during the run; Jev used = the run's unique requests;
OMP = host-reported proposer spend. No Jev or LLM call is made and no test file is opened.

Run from the repo root (v2 and v3 runs may live in other directories):
  uv run --project jev-opt/python python jev-opt/experiments/analyze_tailored.py [--v2-runs DIR] [--v3-runs DIR]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from analyze_v2 import TASKS, bootstrap, configs as v2_configs, hours, jev_cost, omp_cost, run_config, score_fn  # noqa: E402
from analyze_v3 import CHOICES as V3_CHOICES, fresh, select as v3_select  # noqa: E402

ROOT = Path.cwd()
RUNS = ROOT / "runs" / "jev-opt"
OUT = ROOT / "results" / "GEPA_tailored_val.md"
MARGIN = 1.0  # points (x100), as in the third pre-registration: the reading "tailored beats X" needs at least this val margin
V3_REPS = {"A: seed + readout head": ("v3-{stem}-A", "top-quality"), "P: population-opt": ("v3-{stem}-P", "top-single"), "P+head: stacked readout": ("v3-{stem}-P", "top-stacked")}
TAILORED = [  # (row label, run template, representative, comparison row for the Δ column)
    ("tailored", "tailored-{stem}", "top-tailored", "seed fitted: paper"),
    ("tailored-zero", "tailored-{stem}", "top-tailored-zero", "seed as written: paper"),
    ("tailored-head", "tailored-{stem}", "top-tailored-head", "v3 A: seed + readout head"),
    ("tailored, paper start", "tailored-{stem}", "top-tailored-paper", "seed fitted: paper"),
    ("tailored, jev-native start", "tailored-{stem}", "top-tailored-jev-native", "seed fitted: jev-native"),
    ("tailored-zero, paper start", "tailored-{stem}", "top-tailored-zero-paper", "seed as written: paper"),
    ("tailored-zero, jev-native start", "tailored-{stem}", "top-tailored-zero-jev-native", "seed as written: jev-native"),
    ("seed as written: paper", "tailored-{stem}", "top-tailored-seed-paper", None),
    ("seed as written: jev-native", "tailored-{stem}", "top-tailored-seed-jev-native", None),
    ("seed fitted: paper", "tailored-{stem}", "top-tailored-seedfit-paper", None),
    ("seed fitted: jev-native", "tailored-{stem}", "top-tailored-seedfit-jev-native", None),
    ("ablation no T1 (rulebook off), paper start", "tailored-{stem}-noT1", "top-tailored-paper", "tailored, paper start"),
    ("ablation no T1, as written", "tailored-{stem}-noT1", "top-tailored-zero-paper", "tailored-zero, paper start"),
    ("ablation no T2 (GEPA acceptance), paper start", "tailored-{stem}-noT2", "top-tailored-paper", "tailored, paper start"),
    ("ablation no T2, as written", "tailored-{stem}-noT2", "top-tailored-zero-paper", "tailored-zero, paper start"),
]
HEADLINE = [("tailored", ["v2-A: seed + class bias", "v2 best", "v3 chosen"]), ("tailored-zero", ["v1 zero", "v1 text-opt", "v1 program-opt"])]


def load(run_dir: Path, rep: str) -> tuple[dict[str, Any], dict[str, Any]] | None:
    vp = run_dir / "val_predictions.json"
    if not vp.exists():
        return None
    data = json.loads(vp.read_text())
    if rep not in data["representatives"]:
        return None
    return data, json.loads((run_dir / "pareto.json").read_text())["representatives"][rep]


def v1_point(stem: str, kind: str) -> float | None:
    path = RUNS / f"study-{stem}-{kind}" / "pareto.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())["representatives"]["top-quality"]["val"]["primary"]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--v2-runs", type=Path, default=RUNS)
    parser.add_argument("--v3-runs", type=Path, default=RUNS)
    args = parser.parse_args()
    lines = [
        "# jev-tailored dev study: validation results",
        "",
        "Pre-registered (Jev-adapted GEPA). Generated by `jev-opt/experiments/analyze_tailored.py`",
        "from each run's `val_predictions.json`. **Validation split only; no test data was read.** Values ×100; 95%",
        "percentile bootstrap CI over val examples (2,000 resamples, seed 0); Δ = paired bootstrap difference on the",
        "same resamples.",
        "",
        "`jev-tailored` = GEPA text search adapted to Jev (architecture §5.3): Jev rulebook in every proposal (T1),",
        "acceptance on 64 stratified train examples by mean log P(gold) with a 2-point primary-metric guard (T2),",
        "joint rewrites of the most confused, least separable Choice option pair (T3) with minimal pairs (T4),",
        "candidates scored after out-of-fold class biases / cutoffs (T6); one search from the paper seed and one from",
        "the jev-native seed with the best zero-shot train score, OMP budget = the task's v1 program-opt spend. Rows:",
        "`tailored` = best fitted candidate by val (Choice class biases or Score cutoffs + temperature fit on the",
        "400-example train fit slice, like v2-A); `tailored-zero` = best candidate by val run exactly as written",
        "(zero-shot); `tailored-head` = each start's best fitted candidate + readout head (like v3 A), best by val. All",
        "three are selected on this val split (optimistic); the seed rows involve no val choice. v1 rows: point values",
        "of the v1 runs' `top-quality` (no per-example predictions stored).",
        "",
    ]
    costs: list[str] = []
    headline: list[str] = []
    summary: dict[str, Any] = {}
    for stem, title, metric_name in TASKS:
        rows: list[tuple[str, Path, str, dict[str, Any], dict[str, Any]]] = []  # label, run dir, rep, val predictions, pareto entry
        for label, tpl, rep, _ in TAILORED:
            got = load(RUNS / tpl.format(stem=stem), rep)
            if got:
                rows.append((label, RUNS / tpl.format(stem=stem), rep, *got))
        if not rows:
            continue
        cfg = run_config(rows[0][1])
        score = score_fn(cfg)
        gold_ids = sorted(rows[0][3]["gold"])
        gold = [rows[0][3]["gold"][i] for i in gold_ids]
        # comparison rows: v2-A, v2 best (second pre-registration: highest val primary; ties: earlier row), v3 A, v3 chosen
        v2 = [(label, args.v2_runs / run_id, rep, *got) for label, run_id, rep in v2_configs(stem) if (got := load(args.v2_runs / run_id, rep))]
        comp: list[tuple[str, Path, str, dict[str, Any], dict[str, Any]]] = []
        if v2:
            v2_pts = [score(gold, [r[3]["representatives"][r[2]][i] for i in gold_ids]) for r in v2]
            best = int(np.argmax(v2_pts))
            comp += [("v2-A: seed + class bias", *v2[0][1:])] if v2[0][0].startswith("A:") else []
            comp.append((f"v2 best ({v2[best][0]})", *v2[best][1:]))
        v3 = {label: (args.v3_runs / tpl.format(stem=stem), rep, got) for label, (tpl, rep) in V3_REPS.items() if (got := load(args.v3_runs / tpl.format(stem=stem), rep))}
        if "A: seed + readout head" in v3:
            d, rep, got = v3["A: seed + readout head"]
            comp.append(("v3 A: seed + readout head", d, rep, *got))
        chosen = v3_select({label: score(gold, [got[0]["representatives"][rep][i] for i in gold_ids]) for label, (_, rep, got) in v3.items()}) if v3 else None
        if chosen:
            d, rep, got = v3[chosen]
            comp.append((f"v3 chosen ({chosen})", d, rep, *got))
        rows = comp + rows
        for _, _, _, data, _ in rows:
            assert set(data["gold"]) == set(gold_ids), "val sets differ"
        preds = [[data["representatives"][rep][i] for i in gold_ids] for _, _, rep, data, _ in rows]
        boot = bootstrap(gold, preds, score)
        point = [score(gold, p) for p in preds]
        idx = {r[0].split(" (")[0] if r[0].startswith(("v2 best", "v3 chosen")) else r[0]: j for j, r in enumerate(rows)}
        compare = {label: c for label, _, _, c in TAILORED}

        def delta(j: int, k: int | None) -> str:
            if k is None or k == j:
                return ""
            d = boot[:, j] - boot[:, k]
            lo, hi = np.percentile(d, [2.5, 97.5])
            return f"{100 * (point[j] - point[k]):+.1f} ({100 * lo:+.1f}…{100 * hi:+.1f})"

        v1 = {"v1 zero": v1_point(stem, "zero"), "v1 text-opt": v1_point(stem, "text"), "v1 program-opt": v1_point(stem, "program")}
        lines += [f"## {title} ({metric_name}, val n={len(gold)})", "",
                  "| Row | Run / representative | Val (95% CI) | Δ vs | Δ (95% CI) | Jev calls/ex | input tok/ex |", "|---|---|---|---|---|---:|---:|"]
        for label, value in v1.items():
            if value is not None:
                lines.append(f"| {label} | `study-{stem}-{label.split()[-1].replace('-opt', '')}` top-quality | {100 * value:.1f} (point) | | | | |")
        summary[stem] = {"v1": v1}
        for j, (label, run_dir, rep, _, pareto) in enumerate(rows):
            lo, hi = np.percentile(boot[:, j], [2.5, 97.5])
            ref = compare.get(label)
            v = pareto["val"]
            cand = pareto.get("candidate", "")
            member = f" = {cand}" if cand and cand != rep else ""
            lines.append(f"| {label} | `{run_dir.name}` {rep}{member} | **{100 * point[j]:.1f}** ({100 * lo:.1f}…{100 * hi:.1f}) | {ref or ''} | {delta(j, idx.get(ref)) if ref else ''} | {v.get('mean_calls', 0):.2f} | {v.get('mean_input_tokens', 0):.0f} |")
            summary[stem][label] = {"run": run_dir.name, "representative": rep, "candidate": cand, "val": point[j], "ci": [lo, hi]}
        for main_row, refs in HEADLINE:
            if main_row not in idx:
                continue
            j = idx[main_row]
            cells = []
            for r in refs:
                if r in idx:
                    cells.append(f"{r}: {delta(j, idx[r])}")
                elif r in v1 and v1[r] is not None:
                    cells.append(f"{r}: {100 * (point[j] - v1[r]):+.1f} (point)")
            wins = [r for r in refs if (r in idx and 100 * (point[j] - point[idx[r]]) >= MARGIN) or (r in v1 and v1[r] is not None and 100 * (point[j] - v1[r]) >= MARGIN)]
            headline.append(f"| {title} | {main_row} | {100 * point[j]:.1f} | {'; '.join(cells)} | {', '.join(wins) or '—'} |")
        lines.append("")
        for run_dir in dict.fromkeys(r[1] for r in rows if r[1].name.startswith("tailored-")):
            h = hours(run_dir)
            f_cost, f_calls, f_tok = fresh(run_dir)
            costs.append(f"| {title} | `{run_dir.name}` | ${jev_cost(run_dir):.2f} | ${f_cost:.2f} | {f_calls:,} | {f_tok / 1e6:.2f} | ${omp_cost(run_dir):.2f} | {'' if h is None else f'{h:.2f}'} |")
    lines += ["## Headline (val)", "", f"Δ to the comparison rows (paired bootstrap where per-example predictions exist; v1: point). \"≥ {MARGIN:.0f} pt\" lists the rows the tailored row beats by at least {MARGIN:.1f} point (pre-registered reading rule).", "",
              "| Task | Row | Val | Δ | ≥ 1 pt over |", "|---|---|---:|---|---|", *headline, ""]
    lines += ["## Cost per run", "",
              "Jev used: sum of the run's unique Jev requests (fresh or from the shared cache). Jev fresh: billed during this run (requests, M input tokens). OMP: proposer LLM spend reported by the host.", "",
              "| Task | Run | Jev used $ | Jev fresh $ | fresh requests | fresh M tokens | OMP $ | wall h |", "|---|---|---:|---:|---:|---:|---:|---:|", *costs, ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    (RUNS / "tailored-dev-summary.json").write_text(json.dumps(summary, indent=2, default=float))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
