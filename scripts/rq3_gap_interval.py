"""Bootstrap-over-tasks intervals for the RQ3 gap-closed medians (optimization with training labels).

Per configuration: the gap closed by the 3-seed mean of the optimized questions on the paper's single yardstick:
(results/BUDGET_BASELINE.json sets[s].jev.mean - prompt-only) / (paper -
prompt-only), prompt-only = results/frozen.json zero. Medians over the 5 rule-selected sets, the 8 configurations and
all 13, with a 95% percentile interval from B = 10,000 resamples of tasks (numpy default_rng(0), fresh per group).
scripts/paper_answer_table.py takes its intervals from the JSON written here. The three DREsS rubrics are one task:
  A  resampled as one cluster of three configurations, median over all configurations drawn (primary)
  B  collapsed to the mean of their three gaps first
Writes results/RQ3_GAP_INTERVAL.{md,json} and paper/generated/rq3_gap_interval.tex (\\gi* macros).

    uv run scripts/rq3_gap_interval.py [--out DIR]   # DIR replaces paper/generated
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "paper" / "generated"
B = 10_000
DRESS = ("dress-new-content", "dress-new-organization", "dress-new-language")
GROUPS = {"frozen": "Frozen", "opt": "Cfg", "all": "All"}


def clusters(gaps: dict[str, float], collapse: bool) -> list[list[float]]:
    """One list of configuration gaps per task; DREsS is one task (its mean if collapsed)."""
    out = [[g] for s, g in gaps.items() if s not in DRESS]
    dress = [gaps[s] for s in DRESS if s in gaps]
    if dress:
        out.append([float(np.mean(dress))] if collapse else dress)
    return out


def interval(cl: list[list[float]], rng: np.random.Generator) -> dict:
    point = float(np.median([g for c in cl for g in c]))
    draws = rng.integers(0, len(cl), size=(B, len(cl)))
    meds = np.array([np.median([g for i in row for g in cl[i]]) for row in draws])
    lo, hi = np.percentile(meds, [2.5, 97.5])
    return {"median": point, "lo": float(lo), "hi": float(hi), "n_tasks": len(cl), "n_configs": sum(map(len, cl))}


def main() -> None:
    sets = json.loads((ROOT / "results" / "BUDGET_BASELINE.json").read_text())["sets"]
    assert all(len(v["jev"]["test"]) == 3 for v in sets.values()), "every configuration needs 3 optimizer seeds"
    fz = json.loads((ROOT / "results" / "frozen.json").read_text())
    zero = {r["stem"]: r["zero"] for r in fz["orig"] + fz["new"]}
    gap = {s: (v["jev"]["mean"] - zero[s]) / (v["paper"] - zero[s]) for s, v in sets.items()}
    gaps = {g: {s: gap[s] for s, v in sets.items() if g == "all" or v["group"] == g} for g in GROUPS}
    rep = {"rule": "Interval for the RQ3 gap-closed medians (scripts/rq3_gap_interval.py docstring)", "B": B, "seed": 0, "gaps": gaps["all"]}
    for variant, collapse in (("A", False), ("B", True)):
        rep[variant] = {g: interval(clusters(gaps[g], collapse), np.random.default_rng(0)) for g in GROUPS}
    (ROOT / "results" / "RQ3_GAP_INTERVAL.json").write_text(json.dumps(rep, indent=1) + "\n")
    pc = lambda x: f"{100 * x:.0f}"  # noqa: E731
    L = ["# Intervals for the RQ3 gap-closed medians", "",
         "Generated by `scripts/rq3_gap_interval.py`. Gap closed of the 3-seed mean per configuration "
         "from prompt-only Jev (`frozen.json` zero; the paper's single yardstick); 95% percentile interval, bootstrap over tasks, "
         "B = 10,000, default_rng(0) per group. A: DREsS's three "
         "rubrics resampled as one cluster; B: DREsS collapsed to its mean first.", "",
         "| Group | Variant | Tasks | Configurations | Median | 95% interval |", "|---|---|---:|---:|---:|---|"]
    m = {}
    for g, tag in GROUPS.items():
        for variant in ("A", "B"):
            x = rep[variant][g]
            L.append(f"| {g} | {variant} | {x['n_tasks']} | {x['n_configs']} | {pc(x['median'])}% | [{pc(x['lo'])}%, {pc(x['hi'])}%] |")
            v = "" if variant == "A" else "Coll"
            m.update({f"gi{tag}{v}Med": pc(x["median"]), f"gi{tag}{v}Lo": pc(x["lo"]), f"gi{tag}{v}Hi": pc(x["hi"])})
    (ROOT / "results" / "RQ3_GAP_INTERVAL.md").write_text("\n".join(L) + "\n")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "rq3_gap_interval.tex").write_text("% Generated by scripts/rq3_gap_interval.py. Do not edit.\n"
                                              + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    print("\n".join(L))


if __name__ == "__main__":
    main()
