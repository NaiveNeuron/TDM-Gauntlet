"""Page-1 hero (Figure 1): gap closed on the 13 RQ3 configurations, step by step, against fine-tuning on the
same labels.

Writes paper/generated/hero_steps.pdf, paper/generated/hero_steps.tex (\\hs* macros: the medians printed in the
figure, so caption and plot cannot disagree) and results/hero_steps.csv (every value per configuration). Run from
the repo root:

    uv run scripts/paper_fig_hero_steps.py [--out DIR]   # DIR replaces paper/generated

y = gap closed = (score - prompt-only) / (paper's method - prompt-only), the paper's single yardstick (the same
numbers as scripts/paper_answer_table.py). Prompt-only is therefore 0 and the paper's method 100% on every
configuration.

Per configuration, every value comes from a saved results file:
  prompt only       results/frozen.json  {orig,new}[].zero        Jev's prompt-only test score of the 46-set evaluation
                                                                    (DREsS: the rubric's own prompt-only prediction)
  + calibration     results/frozen.json  {orig,new}[].calibrated  per-class biases or a temperature on 400 labels
  + optimized q.    results/BUDGET_BASELINE.json sets[s].jev.mean  mean of 3 optimizer seeds
                                                                    (8 study configurations: = results/seeds.json
                                                                    test_mean; 5 frozen sets: = frozen_seeds.json mean)
  encoder, same     results/BUDGET_BASELINE.json sets[s].best_test_mean  best of 3 trained baselines on the same 500
  labels                                                            train labels, chosen on validation (mean of its seeds)
  LoRA-Qwen, same   results/H100_LORA.json sets[].lora           Qwen3.8-27B + LoRA on the same 500 train labels
  labels                                                          (jev-opt/experiments/analyze_h100_lora.py, seed 0)
  paper's method    paper value in frozen.json (= BUDGET_BASELINE, H100_LORA paper); 100% by definition

Encodings (four): Jev's median line with its interquartile band; one grey line or dot per configuration; the
median and interquartile range of the two same-label fine-tuning methods; the dashed 100% line. Values outside the
y range are drawn at the edge as triangles.
"""

import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.patheffects as pe
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "paper" / "generated"
CSV = ROOT / "results" / "hero_steps.csv"

# Paul Tol 'bright'
BLUE, BLACK, FAINT = "#4477AA", "#222222", "#999999"

STEPS = ["prompt", "cal", "opt"]
FT = ["enc", "lora"]


def load() -> list[dict]:
    rd = lambda p: json.loads((ROOT / p).read_text())  # noqa: E731
    fz = rd("results/frozen.json")
    bb = rd("results/BUDGET_BASELINE.json")["sets"]
    seeds = rd("results/seeds.json")["tasks"]
    fzs = {r["stem"]: r for r in rd("results/frozen_seeds.json")["sets"]}
    lora = {s["set"]: s for s in rd("results/H100_LORA.json")["sets"]}
    rows = []
    for r in fz["orig"] + fz["new"]:
        s = r["stem"]
        b, lo = bb[s], lora[s]
        assert abs(b["paper"] - r["paper"]) < 1e-9 and abs(lo["paper"] - r["paper"]) < 1e-9, s
        opt = b["jev"]["mean"]
        assert len(b["jev"]["test"]) == 3 and abs(b["jev"]["test"][0] - r["optimized"]) < 1e-9, s  # seed 0 = frozen.json
        if r["group"] == "orig":
            assert abs(seeds[s]["test_mean"] - opt) < 1e-9, s
        else:
            assert fzs[s]["n_seeds"] == 3 and abs(fzs[s]["mean"] - opt) < 1e-9, s
        rows.append({"set": s, "name": b["short"], "group": "study" if r["group"] == "orig" else "frozen",
                     "metric": r["metric"], "paper": r["paper"], "prompt": r["zero"], "cal": r["calibrated"],
                     "opt": opt, "enc": b["best_test_mean"], "enc_family": b["best"], "lora": lo["lora"]})
    assert len(rows) == 13
    return rows


def pc(x: float) -> str:
    return f"{x * 100:.0f}"


def macros(Jq: np.ndarray, Eq: np.ndarray, Lq: np.ndarray, n: int) -> str:
    m = [("hsNSets", str(n))]
    for i, k in enumerate(("Prompt", "Cal", "Opt")):
        m += [(f"hsJev{k}", pc(Jq[1, i])), (f"hsJev{k}Lo", pc(Jq[0, i])), (f"hsJev{k}Hi", pc(Jq[2, i]))]
    m += [("hsEnc", pc(Eq[1])), ("hsEncLo", pc(Eq[0])), ("hsEncHi", pc(Eq[2]))]
    m += [("hsLora", pc(Lq[1])), ("hsLoraLo", pc(Lq[0])), ("hsLoraHi", pc(Lq[2]))]
    return ("% Generated by scripts/paper_fig_hero_steps.py (Figure 1 medians, % of the gap closed). Do not edit.\n"
            + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m))


def main() -> None:
    rows = load()
    gap = lambda k: np.array([(r[k] - r["prompt"]) / (r["paper"] - r["prompt"]) for r in rows])  # noqa: E731
    J = np.vstack([gap(k) for k in STEPS])  # 3 x 13, row 0 = 0
    E, L = gap("enc"), gap("lora")
    q = lambda a: np.percentile(a, [25, 50, 75], axis=-1)  # noqa: E731
    Jq, Eq, Lq = q(J), q(E), q(L)

    with open(CSV, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["set", "group", "metric", "paper", "prompt", "cal", "opt", "enc", "enc_family", "lora"]
                   + [f"gap_{k}" for k in ("cal", "opt", "enc", "lora")])
        for j, r in enumerate(rows):
            w.writerow([r["set"], r["group"], r["metric"], r["paper"]] + [f"{r[k]:.4f}" for k in ("prompt", "cal", "opt", "enc")]
                       + [r["enc_family"], f"{r['lora']:.4f}"] + [f"{v:.3f}" for v in (J[1, j], J[2, j], E[j], L[j])])
        for i, k in enumerate(STEPS):
            w.writerow([f"jev_{k}_q25_med_q75"] + [f"{v:.3f}" for v in Jq[:, i]])
        w.writerow(["enc_q25_med_q75"] + [f"{v:.3f}" for v in Eq])
        w.writerow(["lora_q25_med_q75"] + [f"{v:.3f}" for v in Lq])

    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 6.5, "axes.linewidth": 0.5,
                         "xtick.major.width": 0.5, "ytick.major.width": 0.5, "pdf.fonttype": 42})
    fig, ax = plt.subplots(figsize=(3.03, 1.95))
    fig.subplots_adjust(left=0.14, right=0.99, top=0.88, bottom=0.17)
    X = np.array([0, 1, 2])
    XF = np.array([3.1, 4.15])  # encoder, LoRA-Qwen
    YLO, YHI = -0.4, 1.4
    halo = [pe.withStroke(linewidth=1.6, foreground="white")]
    clip = lambda v: np.clip(v, YLO, YHI)  # noqa: E731

    # header strips: what each block needs
    hdr = dict(transform=ax.get_xaxis_transform(), ha="center", va="bottom", fontsize=6.5, color="#444444", clip_on=False)
    ax.axvspan(-0.45, 2.45, color="#EEF2F8", zorder=0, lw=0)
    ax.text(1.0, 1.045, "Jev, no user-managed GPU", **hdr)
    ax.text(XF.mean() - 0.1, 1.045, "fine-tuned, same labels", **hdr)

    # paper's method = 100%
    ax.axhline(1.0, color=BLACK, lw=0.6, ls=(0, (3, 2)), zorder=1)
    ax.text(-0.4, 1.02, "paper's method", fontsize=6.5, color=BLACK, ha="left", va="bottom", zorder=7, path_effects=halo)

    # one grey line (Jev) or dot (fine-tuning) per configuration; off-scale values at the edge as triangles
    for j in range(J.shape[1]):
        ax.plot(X, clip(J[:, j]), color=FAINT, lw=0.5, alpha=0.7, zorder=2, solid_capstyle="round")
    for x, v in ((XF[0], E), (XF[1], L)):
        ax.plot(np.full_like(v, x), clip(v), ls="none", marker="o", ms=1.8, color=FAINT, alpha=0.8, mec="none", zorder=2)
    off = [(X[i], J[i, j]) for i in range(3) for j in range(13) if not YLO <= J[i, j] <= YHI]
    off += [(x, v) for x, a in ((XF[0], E), (XF[1], L)) for v in a if not YLO <= v <= YHI]
    for x, v in off:
        ax.plot([x], [clip(v)], marker="v" if v < YLO else "^", ms=2.6, color=FAINT, zorder=2, clip_on=False)

    # Jev median + interquartile band
    ax.fill_between(X, Jq[0], Jq[2], color=BLUE, alpha=0.25, lw=0, zorder=3)
    ax.plot(X, Jq[1], color=BLUE, lw=2.0, marker="o", ms=3.6, zorder=5)
    for i, (dx, dy, ha, va) in enumerate([(4, -5, "left", "top"), (-3, 4, "right", "bottom"), (5, 0, "left", "center")]):
        if i == 0:
            continue
        ax.annotate(f"{pc(Jq[1, i])}%", (X[i], Jq[1, i]), xytext=(dx, dy), textcoords="offset points", ha=ha, va=va,
                    fontsize=6.5, color=BLUE, path_effects=halo, zorder=7)

    # same-label fine-tuning: median + interquartile range
    for x, a in ((XF[0], Eq), (XF[1], Lq)):
        ax.errorbar([x], [a[1]], yerr=[[a[1] - a[0]], [a[2] - a[1]]], fmt="D", ms=3.4, color=BLACK, mfc="white",
                    mew=0.9, elinewidth=0.9, capsize=1.8, capthick=0.9, zorder=6)
        ax.annotate(f"{pc(a[1])}%", (x, a[1]), xytext=(4, 0), textcoords="offset points", ha="left", va="center",
                    fontsize=6.5, color=BLACK, path_effects=halo, zorder=7)

    ax.set_xlim(-0.45, XF[1] + 0.55)
    ax.set_ylim(YLO, YHI)
    ax.set_xticks([*X, *XF])
    ax.set_xticklabels(["Prompt\nonly", "+ Cali-\nbration", "+ Optimized\nquestions", "Encoder",
                        "LoRA-\nQwen"], fontsize=6.5, linespacing=0.95)
    ax.tick_params(axis="x", length=0, pad=2)
    ax.tick_params(axis="y", length=2, pad=1)
    ax.set_yticks([0, 0.5, 1.0])
    ax.set_yticklabels(["0%", "50%", "100%"])
    ax.set_ylabel("gap closed", fontsize=6.5, labelpad=1)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)

    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / "hero_steps.pdf")
    (OUT / "hero_steps.tex").write_text(macros(Jq, Eq, Lq, len(rows)))
    print("Jev gap [q25, med, q75] per step:", np.round(Jq.T, 3).tolist())
    print("Encoder:", np.round(Eq, 3).tolist(), "LoRA:", np.round(Lq, 3).tolist())
    print("off-scale:", [(round(x, 2), round(v, 2)) for x, v in off])


if __name__ == "__main__":
    main()
