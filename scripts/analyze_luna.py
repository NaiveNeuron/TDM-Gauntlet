        f"`{res['provider']}` on every answered request. Each cohort is Jev's frozen request with only `model` "
        "replaced; same frozen adapters, prompts, calibration rows and metrics as Jev and Clef. Generated by "
        f"`scripts/analyze_luna.py` (B = {res['B']:,}, seed {res['seed']}).", "",
        f"Coverage: {cov['total']} rows; {cov['completed']} completed, {cov['pending']} pending, {cov['blocked']} "
        f"blocked, {cov['noncomparable']} noncomparable, {cov['excluded']} excluded (Wiki-WD, left out of the "
