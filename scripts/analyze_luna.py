# ------------------------------------------------------------------ refusals, rejections, saturation, cost
def _ratio(num: int | float | None, den: int | float | None) -> float | None:
    return None if num is None or not den else num / den


def answer_stats(row: dict) -> dict:
    """The model's answer audit and accounting next to Jev's, for one paired row (None where not recorded)."""
    jm, lm = row["jev"]["manifest"], row["clef"]["manifest"]
    audit = lm.get("answer_audit") if isinstance(lm.get("answer_audit"), dict) else None
    out = {"task": row["task"], "split": row["split"], "status": row["status"], f"{BACKEND}_run": bool(lm),
           "jev_input_tokens": jm.get("input_tokens"), "jev_cost_usd": jm.get("cost_usd"),
           f"{BACKEND}_input_tokens": lm.get("input_tokens"), f"{BACKEND}_cost_usd": lm.get("cost_usd"),
           f"{BACKEND}_snapshots": lm.get("model_snapshots"), "audit": audit}
    if audit is None:
        out.update(refusal_rate=None, saturation_share=None, rejected_share=None)
        return out
    answered = audit.get("n_answers", 0) - audit.get("n_refused_answers", 0)
    out.update(refusal_rate=_ratio(audit.get("n_refused_answers"), audit.get("n_answers")),
               saturation_share=_ratio(audit.get("n_saturated_answers"), answered),
               rejected_share=_ratio(audit.get("n_rejected_requests"), audit.get("n_requests")),
               refused_request_share=_ratio(audit.get("n_refused_requests"), audit.get("n_requests")))
    return out


def totals(stats: list[dict]) -> dict:
    """Sums over the cohorts with a run of the model (any status, dev included); Jev over the same cohorts."""
    ran = [s for s in stats if s[f"{BACKEND}_run"]]
    keys = ("n_requests", "n_rejected_requests", "n_refused_requests", "n_answers", "n_refused_answers",
            "n_saturated_answers")
    audit = {k: sum(int(s["audit"].get(k, 0)) for s in ran if s["audit"]) for k in keys}

    def add(key: str) -> float | int | None:
        values = [s[key] for s in ran if s[key] is not None]
        return sum(values) if values else None
    return {
        "n_cohorts": len(ran), "n_cohorts_with_audit": sum(s["audit"] is not None for s in ran), **audit,
        "refusal_rate": _ratio(audit["n_refused_answers"], audit["n_answers"]),
        "saturation_share": _ratio(audit["n_saturated_answers"], audit["n_answers"] - audit["n_refused_answers"]),
        f"{BACKEND}_input_tokens": add(f"{BACKEND}_input_tokens"), f"{BACKEND}_cost_usd": add(f"{BACKEND}_cost_usd"),
        "jev_input_tokens": add("jev_input_tokens"), "jev_cost_usd": add("jev_cost_usd"),
    }


def spend_ledger(path: Path | None = None) -> dict | None:
    """Billed responses of the model by run label (probes and smoke included, off-pin responses counted)."""
    path = SPEC.spend_ledger if path is None else path
    if not path.exists():
        return None
    by_run: dict[str, dict] = defaultdict(lambda: {"n_responses": 0, "input_tokens": 0, "cost_usd": 0.0})
    offpin = 0
    with open(path, encoding="utf-8") as fh:  # writers (gauntlet.luna.SpendLedger) append under an exclusive lock
        fcntl.flock(fh, fcntl.LOCK_SH)
        try:
            data = fh.read()
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)
    for line in data[:data.rfind("\n") + 1].splitlines():  # complete lines only, as SpendLedger._refresh
        if not line.strip():
            continue
        r = json.loads(line)
        b = by_run[str(r.get("run"))]
        b["n_responses"] += 1
        b["input_tokens"] += int(r.get("input_tokens") or 0)
        b["cost_usd"] += float(r["cost"])
        offpin += r.get("model") != SNAPSHOT or r.get("provider") != PROVIDER
    return {"path": str(path.relative_to(ROOT)), "by_run": dict(sorted(by_run.items())),
            "total_usd": sum(b["cost_usd"] for b in by_run.values()),
            "n_responses": sum(b["n_responses"] for b in by_run.values()), "n_offpin": offpin,
            "total_cap_usd": SPEC.total_cap, "run_caps_usd": SPEC.run_caps}


# ------------------------------------------------------------------ outcome groups (scripts/paper_clef.py)
def summary(rows: dict, tasks: list[str]) -> dict:
    """paper_clef.summary, defined when no set is completed (median None) and with the other statuses counted."""
    ds = [rows[(t, "test")]["delta"] for t in tasks if rows[(t, "test")]["status"] == "completed"]
    out = {"n": len(ds), "better": sum(x > TOL for x in ds), "within": sum(abs(x) <= TOL for x in ds),
           "worse": sum(x < -TOL for x in ds), "median": statistics.median(ds) if ds else None}
    for status in ("pending", "excluded", "blocked", "noncomparable"):
        out[status] = sum(rows[(t, "test")]["status"] == status for t in tasks)
    return out


def outcome_groups(report: dict, causes: dict) -> dict:
    tasks = [t for t, _, _ in PC.table_sets()]
    cause_of = {s["set"]: s["primary"] for s in causes["sets"]}
    ref = {r["task"]: r for r in paper_tables.rows()}
    rows = {(r["task"], r["split"]): r for r in report["rows"]}
    out = {"n_table_sets": len(tasks), "all": summary(rows, tasks)}
    for cause in ("conv", "large"):
        group = [t for t in tasks if cause_of.get(t) == cause]
        # As paper_clef: the below-method count compares the primary metric, so Table full must not use the
        # paper's protocol on these sets.
        if any(ref[t]["protocol"] for t in group):
            raise SystemExit(f"{cause} set scored under the paper's protocol; the below-method count needs it")
        s = summary(rows, group)
        s["n_sets"] = len(group)
        s["below_paper"] = sum(rows[(t, "test")]["clef_value"] < ref[t]["paper"] - 0.005 for t in group
                               if rows[(t, "test")]["status"] == "completed")
        out[cause] = s
    return out


# ------------------------------------------------------------------ (2), (3), (5) as scripts/offline_clef.py
def _rename(value: Any) -> Any:
    """offline_clef's 'clef' keys name the compared model; here that is BACKEND."""
    if isinstance(value, dict):
        return {k.replace("clef", BACKEND): _rename(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_rename(v) for v in value]
    return value


def agreement(sets: list[dict], b: int) -> dict:
    if len({s["paper"] for s in sets}) >= 2:
        with warnings.catch_warnings(), np.errstate(all="ignore"):
            warnings.simplefilter("ignore")
            return _rename(OC.agreement(sets, b))
    # Fewer than two papers (none while runs are pending): no correlation and no paper-clustered interval.
    return {"n_sets": len(sets), "jev_groups": dict(Counter(s["jev_group"] for s in sets)),
            f"{BACKEND}_groups": dict(Counter(s["clef_group"] for s in sets)),
            "crosstab": dict(Counter(f"{s['jev_group']}->{s['clef_group']}" for s in sets)),
            "same_group": sum(s["jev_group"] == s["clef_group"] for s in sets),
            "jev_matches": sum(s["jev_group"] == "replaces" for s in sets),
            "matches_shared": sum(s["jev_group"] == s["clef_group"] == "replaces" for s in sets),
            "spearman_rel": None, "median_delta": None,
            "median_delta_sets": statistics.median(s["delta"] for s in sets) if sets else None}


def analyze(b: int) -> dict:
    report = CR.report(BACKEND)
    causes = json.loads(CAUSES.read_text(encoding="utf-8"))
    sets = OC.completed_sets({BACKEND: report}, BACKEND)
    print(f"{len(sets)} completed Table-full test sets; paired tests ({LABEL} vs Jev)", flush=True)
    paired = OC.paired(sets, b)
    stats = [answer_stats(r) for r in report["rows"]]
    context: dict[str, dict] = {}
    if CONTEXT.exists():
        d = json.loads(CONTEXT.read_text(encoding="utf-8"))
        for model in CONTEXT_MODELS:
            context[model] = {"pin": f"{d[model]['clef_model']}@{d[model]['clef_revision']}",
                              "outcome_groups": outcome_groups(d[model], causes),
                              "rows": {f"{r['task']}|{r['split']}": {"value": r["clef_value"], "delta": r["delta"],
                                                                     "status": r["status"]} for r in d[model]["rows"]}}
    for model in CFG["api_context"]:  # another API model's own comparison (results/<MODEL>_COMPARISON.json)
        path = RESULTS / f"{model.upper()}_COMPARISON.json"
        if path.exists():
            context[model] = api_context(json.loads(path.read_text(encoding="utf-8")), causes)
    rows = report.pop("rows")
    return {
        **report, "provider": PROVIDER, "generated_by": "scripts/analyze_luna.py", "B": b, "seed": OC.SEED,
        "outcome_groups": outcome_groups({"rows": rows}, causes),
        "agreement": agreement(sets, b), "agreement_sets": _rename(sets), "paired": _rename(paired),
        "answers": {"rows": stats, "totals": totals(stats)}, "spend_ledger": spend_ledger(),
        "context": context, "rows": rows,
    }


def api_context(d: dict, causes: dict) -> dict:
    """Context block from another API model's comparison JSON (its own cohort checks and statuses)."""
    return {"pin": f"{d['clef_model']}@{d['clef_revision']}", "outcome_groups": outcome_groups({"rows": d["rows"]}, causes),
            "rows": {f"{r['task']}|{r['split']}": {"value": r["clef_value"], "delta": r["delta"], "status": r["status"],
                                                   "scores": r["clef"]["scores"] if r["task"] in PC.CICC else None}
                     for r in d["rows"]}}


# ------------------------------------------------------------------ macros
def _pct(x: float | None, nd: int = 1) -> str:
    return "--" if x is None else PC.num(100 * x, nd)


def _n(x: float | None, nd: int) -> str:
    return "--" if x is None else PC.num(x, nd)


def macros(res: dict) -> str:
    rows = {(r["task"], r["split"]): r for r in res["rows"]}
    tasks = [t for t, _, _ in PC.table_sets()]
    cov, og = res["coverage"], res["outcome_groups"]
    m: dict[str, str] = {
        f"{PFX}Snapshot": SNAPSHOT if res["clef_revision"] == SNAPSHOT else res["clef_revision"],
        f"{PFX}Provider": res["provider"],
        f"{PFX}NCohorts": str(cov["total"]), f"{PFX}NCompleted": str(cov["completed"]), f"{PFX}NExcluded": str(cov["excluded"]),
        f"{PFX}NNoncomparable": str(cov["noncomparable"]),
        f"{PFX}NSets": str(og["all"]["n"]), f"{PFX}NPending": str(og["all"]["pending"]),
        f"{PFX}Better": str(og["all"]["better"]), f"{PFX}Within": str(og["all"]["within"]), f"{PFX}Worse": str(og["all"]["worse"]),
        f"{PFX}Median": _pct(og["all"]["median"]),
    }
    done = [r for r in res["rows"] if r["status"] == "completed"]
    test = [r for r in done if r["split"] == "test"]
    m[f"{PFX}NTestCohorts"] = str(len(test))
    m[f"{PFX}NSuppTest"] = str(sum(r["task"] not in tasks for r in test))
    m[f"{PFX}NDevCohorts"] = str(len(done) - len(test))
    out = res["test_outcomes"]
    m[f"{PFX}ExactWins"], m[f"{PFX}ExactTies"], m[f"{PFX}ExactLosses"] = str(out["wins"]), str(out["ties"]), str(out["losses"])
    for cause, cname in (("conv", "Conv"), ("large", "Large")):
        s = og[cause]
        for key, name in (("n", "N"), ("worse", "Worse"), ("better", "Better"), ("within", "Within"),
                          ("below_paper", "BelowPaper")):
            m[f"{PFX}{cname}{name}"] = str(s[key])
        m[f"{PFX}{cname}Median"] = _pct(s["median"])
    sc = {t: rows[(t, "test")]["clef"]["scores"] for t in PC.CICC if rows[(t, "test")]["status"] == "completed"}
    m[f"{PFX}CiccNSets"] = str(len(PC.CICC))
    m[f"{PFX}CiccNCompleted"] = str(len(sc))
    m[f"{PFX}CiccNFull"] = str(sum(v["qhat"] >= 1.0 for v in sc.values()))
    for t, g in CICC_GROUPS:
        v = sc.get(t)
        m[f"{PFX}Cicc{g}"] = _pct(v["single"] if v else None)
        m[f"{PFX}Cicc{g}Acc"] = _pct(v["accuracy"] if v else None)
        m[f"{PFX}Cicc{g}Size"] = _n(v["mean_set_size"] if v else None, 2)
    b77 = rows[("cicc/b77", "test")]
    m[f"{PFX}CiccBSevenSeven"] = _pct(b77["clef_value"] if b77["status"] == "completed" else None)
    tot = res["answers"]["totals"]
    m[f"{PFX}NRequests"], m[f"{PFX}NRejected"] = str(tot["n_requests"]), str(tot["n_rejected_requests"])
    m[f"{PFX}NRefusedRequests"] = str(tot["n_refused_requests"])
    # Refusals at request level (a refused request answers every question uniformly) and the cohort they gather in.
    m[f"{PFX}RefusedRequestRate"] = _pct(tot["n_refused_requests"] / tot["n_requests"], 2)
    top = max((s for s in res["answers"]["rows"] if s["audit"]), key=lambda s: s["audit"].get("n_refused_requests", 0))
    m[f"{PFX}RefusedTopRate"] = _pct(top["audit"]["n_refused_requests"] / top["audit"]["n_requests"], 1)
    m[f"{PFX}RefusedTopShare"] = _pct(_ratio(top["audit"]["n_refused_requests"], tot["n_refused_requests"]), 1)
    m[f"{PFX}NAnswers"], m[f"{PFX}NRefused"] = str(tot["n_answers"]), str(tot["n_refused_answers"])
    m[f"{PFX}RefusalRate"] = _pct(tot["refusal_rate"], 2)
    m[f"{PFX}SaturationShare"] = _pct(tot["saturation_share"])
    m[f"{PFX}InputTokensM"] = _n(None if tot[f"{BACKEND}_input_tokens"] is None else tot[f"{BACKEND}_input_tokens"] / 1e6, 1)
    m[f"{PFX}Cost"] = _n(tot[f"{BACKEND}_cost_usd"], 2)
    m[f"{PFX}JevCost"] = _n(tot["jev_cost_usd"], 2)
    ledger = res["spend_ledger"]
    m[f"{PFX}Spend"] = _n(ledger["total_usd"] if ledger else None, 2)
    for label, name in (("zero-shot", "ZeroShot"), ("rq3", "RqThree")):
        m[f"{PFX}Spend{name}"] = _n(ledger["by_run"].get(label, {}).get("cost_usd") if ledger else None, 2)
    a = res["agreement"]
    m[f"{PFX}AgreeNSets"], m[f"{PFX}SameGroup"] = str(a["n_sets"]), str(a["same_group"])
    m[f"{PFX}JevMatches"], m[f"{PFX}MatchesShared"] = str(a["jev_matches"]), str(a["matches_shared"])
    rho, med = a["spearman_rel"], a["median_delta"]
    m[f"{PFX}Rho"] = _n(rho["point"] if rho else None, 2)
    m[f"{PFX}RhoLo"] = _n(rho["lo"] if rho else None, 2)
    m[f"{PFX}RhoHi"] = _n(rho["hi"] if rho else None, 2)
    m[f"{PFX}MedLo"] = "--" if med is None else PC.num(100 * med["lo"], 1, sign=True)
    m[f"{PFX}MedHi"] = "--" if med is None else PC.num(100 * med["hi"], 1, sign=True)
    m[f"{PFX}NPapers"] = str(med["n_papers"]) if med else "0"
    p = res["paired"]
    m[f"{PFX}PairNTested"], m[f"{PFX}PairNHigher"], m[f"{PFX}PairNLower"] = str(p["n_tested"]), str(p["n_higher"]), str(p["n_lower"])
    m[f"{PFX}PairNSep"] = str(p["n_higher"] + p["n_lower"])
    for name, inf in (("intent", "Intent"), ("other", "Other")):
        s = p["by_intent"][name]
        m[f"{PFX}Pair{inf}NTested"], m[f"{PFX}Pair{inf}NHigher"] = str(s["n_tested"]), str(s["n_higher"])
        m[f"{PFX}Pair{inf}NLower"] = str(s["n_lower"])
    return "\n".join([HEADER] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]) + "\n"


# ------------------------------------------------------------------ markdown
_fmt, _table = CR._fmt, CR._table


def _p(x: float | None, nd: int = 1, sign: bool = False) -> str:
    return "—" if x is None else (f"{100 * x:+.{nd}f}" if sign else f"{100 * x:.{nd}f}")


def _usd(x: float | None) -> str:
    return "—" if x is None else f"${x:,.4f}"


def _tokens(x: int | None) -> str:
    return "—" if x is None else f"{x:,}"


def _interval(ci: dict | None, scale: float = 1, nd: int = 2) -> str:
    if ci is None:
        return "— (fewer than two papers)"
    return f"{scale * ci['point']:.{nd}f} [{scale * ci['lo']:.{nd}f}, {scale * ci['hi']:.{nd}f}] ({ci['n_papers']} papers)"


def cicc_section(res: dict, api_ctx: list[str]) -> list[str]:
    """CICC conformal sets: the model's unrounded probabilities next to Jev's (and Luna's) two-decimal ones."""
    rows = {(r["task"], r["split"]): r for r in res["rows"]}
    out = ["", "## CICC: conformal sets from unrounded probabilities", "",
           f"{LABEL} returns probabilities at full precision; Jev and Luna round to two decimals, so many options tie and "
           "the conformal threshold q̂ can reach 1 (every option in the set). Per CICC set: primary metric (single-"
           "answer coverage, `single`), accuracy, mean set size and q̂ on the test split.", ""]
    body = []
    for t in PC.CICC:
        r = rows.get((t, "test"))
        if r is None:
            continue
        cols = [("Jev", r["jev"]["scores"] if r["jev"]["scores"] else None),
                (LABEL, r["clef"]["scores"] if r["status"] == "completed" else None)]
        cols += [(SPECS[m].label, res["context"][m]["rows"].get(f"{t}|test", {}).get("scores")) for m in api_ctx]
        for label, sc in cols:
            sc = sc or {}
            body.append([t, label, _p(sc.get("single")), _p(sc.get("accuracy")),
                         "—" if sc.get("mean_set_size") is None else f"{sc['mean_set_size']:.2f}",
                         "—" if sc.get("qhat") is None else f"{sc['qhat']:.4f}"])
    return out + _table(["Set", "Model", "Single (%)", "Accuracy (%)", "Mean set size", "q̂"], body)


