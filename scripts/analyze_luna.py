def write(res: dict) -> None:
    OUT_MD.write_text(markdown(res), encoding="utf-8")
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text(macros(res), encoding="utf-8")


def main() -> None:
    model = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--model=")), None)
    if "--model" in sys.argv[1:]:
        model = sys.argv[sys.argv.index("--model") + 1]
    configure(model or "luna")
    if "--report-only" in sys.argv[1:]:
        res = json.loads(OUT_JSON.read_text(encoding="utf-8"))
        res["spend_ledger"] = spend_ledger()
        # Outcome groups follow the current cause table (results/causes.json), which can change after the run.
        causes = json.loads(CAUSES.read_text(encoding="utf-8"))
        res["outcome_groups"] = outcome_groups({"rows": res["rows"]}, causes)
        if CONTEXT.exists():
            d = json.loads(CONTEXT.read_text(encoding="utf-8"))
            for model in res.get("context", {}):
                if model in d:
                    res["context"][model]["outcome_groups"] = outcome_groups(d[model], causes)
        for model in CFG["api_context"]:
            path = RESULTS / f"{model.upper()}_COMPARISON.json"
            if model in res.get("context", {}) and path.exists():
                res["context"][model] = api_context(json.loads(path.read_text(encoding="utf-8")), causes)
        OUT_JSON.write_text(json.dumps(CR._safe(res), indent=1, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
        write(res)
        return
    b = next((int(a.split("=", 1)[1]) for a in sys.argv[1:] if a.startswith("--B=")), OC.B)
    t0 = time.time()
    res = analyze(b)
    res["seconds"] = round(time.time() - t0)
    print(json.dumps({"coverage": res["coverage"], "test_outcomes": res["test_outcomes"],
                      "outcome_groups": res["outcome_groups"]["all"], "paired": {k: v for k, v in res["paired"].items() if k not in ("rows", "skipped")},
                      "answers": res["answers"]["totals"]}, indent=1))
    if b != OC.B:
        return
    OUT_JSON.write_text(json.dumps(CR._safe(res), indent=1, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
    write(res)


if __name__ == "__main__":
    main()
