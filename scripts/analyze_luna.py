"""Zero-shot Jev / GPT-6 Luna contrast (no model calls), and with `--model msd1` the Jev / Microsoft-Decision-1
contrast (results/MSD1_COMPARISON.{json,md}, paper/generated/msd1.tex with \\ms* macros, Luna's
results/LUNA_COMPARISON.json as context, and a CICC table of the conformal sets from MSD1's unrounded probabilities
next to Jev's and Luna's two-decimal ones).

Inputs: the paired comparison `gauntlet.clef_report.report("luna")` (runs/ and runs/luna/: cohort checks, pinned
snapshot on every response, rejected requests at most 1% of a cohort, sign outcomes; Wiki-WD excluded), the Luna
manifests' `answer_audit` (refusals, rejections, saturation), the shared spend ledger runs/luna/spend.jsonl,
results/causes.json (primary causes), scripts/paper_tables.py (Table full) and, as context only,
results/decision_models_comparison.json (Clef, Clef-flash).

Analyses, exactly as for Clef with Luna in Clef's place:
- Outcome groups on the Table-full test sets with a completed run (scripts/paper_clef.py): better / within / worse
  at one point, median delta, pending count; the same by primary cause (conventions, large label spaces), with the
  number of those sets below the paper's method (0.5-point tolerance).
- scripts/offline_clef.py (2) agreement / RQ1 groups, Spearman correlation relative to the paper's method and
  median delta with paper-clustered 95% intervals; (3) per-set paired bootstrap, Holm over the sets; (5) the
  separations split by intent-detection sets. B = 10,000, numpy default_rng(0).
- Per cohort: refusal rate (refused / answers), rejected requests, saturation share (saturated / answers not
  refused), input tokens and API dollars for Jev and Luna.

Writes results/LUNA_COMPARISON.{json,md} and results/luna.tex (\\lu* macros; '--' where a value is undefined, for
example while runs are pending). Run from the repo root:

    uv run python scripts/analyze_luna.py              # full analysis
    uv run python scripts/analyze_luna.py --B=200      # dry run, writes nothing
    uv run python scripts/analyze_luna.py --report-only  # rewrite json spend block and outcome groups (current ledger
                                                         # and causes), md and tex
    uv run python scripts/analyze_luna.py --model msd1 [--B=200|--report-only]   # the same for MSD1
"""

