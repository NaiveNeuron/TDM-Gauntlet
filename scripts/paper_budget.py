"""Label-budget macros for the optimized step, read from the generated opt-data table.

Writes paper/generated/budget.tex. Source: the Train / Val / Fit slice columns of
Table tab:opt-data in paper/generated/app_opt.tex (itself generated from the experiment data).
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper/generated/app_opt.tex"
OUT = ROOT / "paper/generated/budget.tex"


def main() -> None:
    text = SRC.read_text()
    table = text[text.index(r"\label{app:opt-data}") : text.index(r"\label{tab:opt-data}")]
    rows = []
    for line in table.splitlines():
        cells = [c.strip() for c in line.rstrip("\\ ").split("&")]
        if len(cells) == 9 and cells[3].replace(",", "").isdigit():
            train, val, fit = (int(cells[i].replace(",", "")) for i in (3, 4, 6))
            rows.append((train, val, fit))
    assert len(rows) == 8, rows
    trains = {r[0] for r in rows}
    fits = {r[2] for r in rows}
    assert len(trains) == 1 and len(fits) == 1, (trains, fits)
    train, fit = trains.pop(), fits.pop()
    vals = [r[1] for r in rows]
    fmt = lambda n: f"{n:,}"
    macros = {
        "optTrainN": fmt(train),
        "optReflN": fmt(train - fit),
        "optValMin": fmt(min(vals)),
        "optValMax": fmt(max(vals)),
        "optLabelsMin": fmt(train + min(vals)),
        "optLabelsMax": fmt(train + max(vals)),
    }
    body = "% Generated by scripts/paper_budget.py. Do not edit.\n" + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()
    )
    OUT.write_text(body)
    print(body)


if __name__ == "__main__":
    main()
