"""Paper macros and appendix table for the zero-shot Jev / Clef / Clef-flash / Luna contrast.

Reads results/decision_models_comparison.json (`gauntlet compare-clef`), results/LUNA_COMPARISON.json
(scripts/analyze_luna.py) and results/causes.json (scripts/cause_table.py) and writes paper/generated/clef.tex
(\\cl* macros) and paper/generated/app_clef.tex (Table tab:clef). Run from the repo root:

    uv run python scripts/paper_clef.py

Body counts use the test sets of Table tab:full (scripts/paper_tables.py DATASETS) that have a completed
run of the model. Deltas are model minus Jev in points on each set's primary metric, scored the same way for
every model; "within a point" means |delta| <= 1 point.
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_appendix  # noqa: E402
import paper_tables  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "generated"
SRC = ROOT / "results" / "decision_models_comparison.json"
CAUSES = ROOT / "results" / "causes.json"
LUNA = ROOT / "results" / "LUNA_COMPARISON.json"
HEADER = "% Generated by scripts/paper_clef.py from results/decision_models_comparison.json. Do not edit."

MODELS = {"clef": "", "clef-flash": "Flash"}  # comparison key -> macro infix
TOL = 0.01  # one point, on the 0-1 scale of every primary metric
CICC = ("cicc/mtod", "cicc/hwu64", "cicc/c150", "cicc/acid", "cicc/atis")  # the compared CICC sets (Table full)
CAUSE_SHORT = {"conv": "conv.", "large": "large", "coarse": "coarse", "other": "other"}
# The body names the convention sets on which Clef is more than a point lower; fail loudly if that changes.
CONV_WORSE_NAMED = {"ezstance/subtaskA", "ezstance/subtaskB", "inli", "smarter/latent_hate", "smarter/hatexplain",
                    "dress_new", "contempo/tbdense", "ttp/expert"}
SUPP_METRIC = {"expl_rank": "nDCG@5", "cicc/b77": "Single", "cicc/c150_oos": "OOS F1", "cicc/b77_oos": "OOS F1",
               "ttp/expert_full": "P@1", "biorc800/dev": "micro-F1"}


def rows_by_task(d: dict, model: str) -> dict[tuple[str, str], dict]:
    return {(r["task"], r["split"]): r for r in d[model]["rows"]}


def table_sets() -> list[tuple[str, str, str]]:
    return [(t, name, paper_tables.METRIC_TEX.get(paper_tables.PAPER[t]["metric"], paper_tables.PAPER[t]["metric"]))
            for t, _, name, *_ in paper_tables.DATASETS]


def num(x: float, nd: int = 1, sign: bool = False) -> str:
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    if s.startswith("-"):
        return "$-$" + s[1:]
    return s


def pts(x: float | None) -> str:
    return "--" if x is None else num(100 * x, 1)


def dpts(x: float | None) -> str:
    return "--" if x is None else num(100 * x, 1, sign=True)


def summary(rows: dict, tasks: list[str]) -> dict:
    ds = [rows[(t, "test")]["delta"] for t in tasks if rows[(t, "test")]["status"] == "completed"]
    return {"n": len(ds), "better": sum(x > TOL for x in ds), "within": sum(abs(x) <= TOL for x in ds),
            "worse": sum(x < -TOL for x in ds), "median": statistics.median(ds),
            "pending": sum(rows[(t, "test")]["status"] == "pending" for t in tasks)}


def macros(d: dict, causes: dict) -> str:
    tasks = [t for t, _, _ in table_sets()]
    cause_of = {s["set"]: s["primary"] for s in causes["sets"]}
    ref = {r["task"]: r for r in paper_tables.rows()}  # task-specific method value, as in Table full
    m: dict[str, str] = {}
    for model, inf in MODELS.items():
        rows = rows_by_task(d, model)
        cov = d[model]["coverage"]
        s = summary(rows, tasks)
        m[f"cl{inf}NCohorts"] = str(cov["total"])
        m[f"cl{inf}NCompleted"] = str(cov["completed"])
        m[f"cl{inf}NSets"] = str(s["n"])
        m[f"cl{inf}NPending"] = str(s["pending"])
        m[f"cl{inf}Better"] = str(s["better"])
        m[f"cl{inf}Within"] = str(s["within"])
        m[f"cl{inf}Worse"] = str(s["worse"])
        m[f"cl{inf}Median"] = num(100 * s["median"])
        # Reconciles the released comparison's counts (all completed test cohorts, exact signs) with the table's.
        done = [r for r in d[model]["rows"] if r["status"] == "completed"]
        test = [r for r in done if r["split"] == "test"]
        m[f"cl{inf}NTestCohorts"] = str(len(test))
        m[f"cl{inf}NSuppTest"] = str(sum(r["task"] not in tasks for r in test))
        m[f"cl{inf}NDevCohorts"] = str(len(done) - len(test))
        out = d[model]["test_outcomes"]
        if out["comparable"] != len(test) or out["ties"] or out["unknown_direction"]:
            raise SystemExit(f"{model}: test_outcomes do not cover the completed test cohorts by sign")
        m[f"cl{inf}ExactWins"] = str(out["wins"])
        m[f"cl{inf}ExactLosses"] = str(out["losses"])
        m[f"cl{inf}Rev"] = d[model]["clef_revision"][:7]
        rev = d[model]["clef_revision"]  # 40 hex digits: allow line breaks every 8 so the column does not overflow
        m[f"cl{inf}RevFull"] = "\\allowbreak{}".join(rev[i:i + 8] for i in range(0, len(rev), 8))
        for cause, cname in (("conv", "Conv"), ("large", "Large")):
            cs = [rows[(t, "test")]["delta"] for t in tasks
                  if cause_of.get(t) == cause and rows[(t, "test")]["status"] == "completed"]
            m[f"cl{inf}{cname}N"] = str(len(cs))
            m[f"cl{inf}{cname}Worse"] = str(sum(x < -TOL for x in cs))
            m[f"cl{inf}{cname}Better"] = str(sum(x > TOL for x in cs))
            m[f"cl{inf}{cname}Within"] = str(sum(abs(x) <= TOL for x in cs))
            m[f"cl{inf}{cname}Median"] = num(100 * statistics.median(cs))
            # Below the paper's method by the Table-full rule (match = within 0.5 points). Only sets where Table full
            # does not use the paper's protocol for Jev, so the model's primary metric is the compared quantity.
            if any(ref[t]["protocol"] for t in tasks if cause_of.get(t) == cause):
                raise SystemExit(f"{cause} set scored under the paper's protocol; the below-method count needs it")
            m[f"cl{inf}{cname}BelowPaper"] = str(sum(
                rows[(t, "test")]["clef_value"] < ref[t]["paper"] - 0.005 for t in tasks
                if cause_of.get(t) == cause and rows[(t, "test")]["status"] == "completed"))
            if m[f"cl{inf}{cname}BelowPaper"] != m[f"cl{inf}{cname}N"]:
                raise SystemExit(f"{model} matches a paper's method on a {cause} set; the text says all stay below")
        sc = {t: rows[(t, "test")]["clef"]["scores"] for t in CICC}
        m[f"cl{inf}CiccNSets"] = str(len(CICC))
        m[f"cl{inf}CiccNFull"] = str(sum(v["qhat"] >= 1.0 for v in sc.values()))
        for t, g in (("cicc/c150", "Clinc"), ("cicc/acid", "Acid"), ("cicc/atis", "Atis"), ("cicc/hwu64", "Hwu"),
                     ("cicc/mtod", "Mtod")):
            m[f"cl{inf}Cicc{g}"] = pts(sc[t]["single"])
            m[f"cl{inf}Cicc{g}Acc"] = pts(sc[t]["accuracy"])
            m[f"cl{inf}Cicc{g}Size"] = num(sc[t]["mean_set_size"], 2)
        m[f"cl{inf}CiccBSevenSeven"] = pts(rows[("cicc/b77", "test")]["clef_value"])
        if model == "clef":
            worse = {t for t in tasks if cause_of.get(t) == "conv" and rows[(t, "test")]["status"] == "completed"
                     and rows[(t, "test")]["delta"] < -TOL}
            if worse != CONV_WORSE_NAMED:
                raise SystemExit(f"convention sets with Clef > 1 point lower changed: {sorted(worse)}; update the body")
            ws = [-100 * rows[(t, "test")]["delta"] for t in worse]
            m["clConvWorseMin"] = num(min(ws))
            m["clConvWorseMax"] = num(max(ws))
            jsc = {t: rows[(t, "test")]["jev"]["scores"] for t in CICC}
            m["clJevCiccNFull"] = str(sum(v["qhat"] >= 1.0 for v in jsc.values()))
            m["clJevCiccClincSize"] = num(jsc["cicc/c150"]["mean_set_size"], 0)
            nyt = rows[("relemb/nytfb", "test")]
            if not nyt["protocol_deviations"]:
                raise SystemExit("NYT-FB guard deviation missing from the comparison; update the appendix")
    return "\n".join([HEADER] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]) + "\n"


NOT_RUN = {"relemb/wikiwd"}  # not run locally because of its size (2.5B input tokens for Jev)


def note(r: dict) -> str:
    if r["status"] == "pending":
        return "not run (size)" if r["task"] in NOT_RUN else "pending"
    if r["status"] != "completed":
        return r["status"]
    if any("65536" in p for p in r["protocol_deviations"]):
        return "limit 65,536"
    if r["protocol_deviations"]:
        raise SystemExit(f"unlabelled protocol deviation on {r['task']}: {r['protocol_deviations']}")
    return ""


def table(d: dict, causes: dict, luna_d: dict) -> str:
    cause_of = {s["set"]: s["primary"] for s in causes["sets"]}
    clef, flash = rows_by_task(d, "clef"), rows_by_task(d, "clef-flash")
    luna = {(r["task"], r["split"]): r for r in luna_d["rows"]}
    keys = set(clef)
    if keys != set(flash) or keys != set(luna):
        raise SystemExit("Clef, Clef-flash and Luna cover different cohorts")
    main = [((t, "test"), name, metric) for t, name, metric in table_sets()]
    supp = [((t, "dev" if t.endswith("/dev") else "test"), name, SUPP_METRIC[t])
            for t, name, *_ in paper_appendix.SUPPLEMENTARY]
    listed = {k for k, _, _ in main + supp}
    if listed != keys:
        raise SystemExit(f"cohorts not in the table: {sorted(keys - listed)}; unknown: {sorted(listed - keys)}")

    def line(key: tuple[str, str], name: str, metric: str) -> str:
        c, f, lu = clef[key], flash[key], luna[key]
        if lu["jev_value"] is not None and c["jev_value"] is not None and abs(lu["jev_value"] - c["jev_value"]) > 1e-9:
            raise SystemExit(f"Jev value differs between the Clef and Luna comparisons on {key}")
        notes = sorted({n for n in (note(c), note(f), "not run (size)" if lu["status"] == "excluded" else note(lu)) if n})
        cause = CAUSE_SHORT.get(cause_of.get(key[0], ""), "--")
        return (f"{name} & {metric} & {cause} & {pts(c['jev_value'])} & {pts(c['clef_value'])} & {dpts(c['delta'])} & "
                f"{pts(f['clef_value'])} & {dpts(f['delta'])} & {pts(lu['clef_value'])} & {dpts(lu['delta'])} & "
                f"{'; '.join(notes)} \\\\")

    lines = [HEADER, "\\begin{table*}[!tp]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{4pt}",
             "\\renewcommand{\\arraystretch}{0.97}",
             "\\begin{tabular}{@{}lllrrrrrrrl@{}}", "\\toprule",
             "Set & Metric & Cause & \\jev{} & Clef & $\\Delta$ & Flash & $\\Delta$ & Luna & $\\Delta$ & Note \\\\", "\\midrule",
             f"\\multicolumn{{11}}{{@{{}}l}}{{\\textit{{Test sets of Table~\\ref{{tab:full}}}}}} \\\\"]
    lines += [line(*x) for x in main]
    lines += ["\\midrule", f"\\multicolumn{{11}}{{@{{}}l}}{{\\textit{{Supplementary runs (Table~\\ref{{tab:supp}})}}}} \\\\"]
    lines += [line(*x) for x in supp]
    notes = {note(r) for r in list(clef.values()) + list(flash.values())}
    legend = ""
    if "not run (size)" in notes or any(r["status"] == "excluded" for r in luna.values()):
        legend += ("Not run (size): Wiki-WD, too large to run locally or to pay for on Luna (\\bodyWikiTokensB{} "
                   "billion input tokens for \\jev{}). ")
    if "pending" in notes:
        legend += "Pending: no completed run, not a failure. "
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\caption{Zero-shot scores ($\\times$100) of \\jev{}, Clef, Clef-flash (Flash) and GPT-6 Luna Decisions on "
              "\\jev{}'s frozen requests, for every cohort of the comparison, grouped by paper. "
              "$\\Delta$: model minus \\jev{}, in points. All four models are scored with each set's primary "
              "metric. Where Table~\\ref{tab:full} marks \\jev{} with $^\\dagger$, it reports the paper's protocol, "
              "so its value differs from the one here. Cause: primary cause of \\jev{}'s shortfall "
              f"(Table~\\ref{{tab:causes}}). {legend}Limit 65,536: complete inputs "
              "of up to 65,536 tokens instead of the 32,000 used elsewhere, because NYT-FB's complete requests "
              "exceed 32,000 tokens in the Clef encoding. This deviates from the initial protocol and is "
              "not an equal-context comparison with \\jev{}'s API. No input is truncated.}",
              "\\label{tab:clef}", "\\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    d = json.loads(SRC.read_text())
    causes = json.loads(CAUSES.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "clef.tex").write_text(macros(d, causes))
    (OUT / "app_clef.tex").write_text(table(d, causes, json.loads(LUNA.read_text())))


if __name__ == "__main__":
    main()
