"""Integrate the offline v4 analyses into results/OFFLINE_V4.{md,json} and paper/generated/offline.tex.

Inputs: results/offline_v4/<slug>.json written by scripts/offline_<slug>.py (rq1, rq3, hybrid,
calib_budget, conf_ctrl). Each has "macros" ({name: LaTeX string}, names start with "ov") and
"md" (a markdown section). No computation happens here; missing slices are listed, not invented.
"""
import json
import sys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SLUGS = ["rq1", "rq3", "hybrid", "calib_budget", "conf_ctrl"]


def main():
    macros, sections, missing, combined = {}, [], [], {}
    for slug in SLUGS:
        p = ROOT / "results" / "offline_v4" / f"{slug}.json"
        if not p.exists():
            missing.append(slug)
            continue
        d = json.loads(p.read_text())
        combined[slug] = d
        for k, v in d.get("macros", {}).items():
            if not re.fullmatch(r"ov[A-Za-z]+", k):
                raise ValueError(f"{slug}: bad macro name {k}")
            if k in macros:
                raise ValueError(f"duplicate macro {k}")
            macros[k] = str(v)
        sections.append(d["md"].strip())
        if slug == "rq3":  # off-the-shelf GEPA medians, from the saved gap summary (results/offline_v4/rq3.json)
            for key, name in (("v1 text-opt", "GepaText"), ("v1 program-opt", "GepaProg"), ("v2", "Vtwo")):
                g = d["gap_summary"][key]
                for stat, suffix in (("median_sets", "GapMedian"), ("median_papers", "GapMedianPaper")):
                    k = f"ovRqThree{name}{suffix}"
                    if k not in macros:
                        macros[k] = f"{100 * g[stat]:.0f}"
    head = ("# Offline analyses v4\n\nGenerated by `scripts/offline_v4_report.py` from "
            "`results/offline_v4/*.json`. Offline only: saved predictions/responses and the "
            "jev-opt cache in cache-only mode; no Jev or LLM call.\n")
    if missing:
        head += "\nMissing slices: " + ", ".join(missing) + "\n"
    (ROOT / "results" / "OFFLINE_V4.md").write_text(head + "\n" + "\n\n".join(sections) + "\n")
    (ROOT / "results" / "OFFLINE_V4.json").write_text(
        json.dumps({"macros": macros, "missing": missing, "slices": combined}, indent=1))
    tex = "% Generated by scripts/offline_v4_report.py from results/offline_v4/*.json. Do not edit.\n"
    tex += "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(macros.items()))
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "paper" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    (out / "offline.tex").write_text(tex)
    print(len(macros), "macros; missing:", missing)


if __name__ == "__main__":
    main()
