"""LoRA fine-tuning and effort numbers of the paper -> paper/generated/lora.tex (\\lr* and \\ef* macros) and
paper/generated/app_lora.tex (appendix table of the 13 sets).

Assembles, without recomputing any test score or bootstrap, the saved outputs of:
  results/H100_LORA.json                jev-opt/experiments/analyze_h100_lora.py (Qwen3.8-27B + LoRA on the same
                                        500 training labels: scores, paired contrasts, gap closed, GPU hours, memory)
  results/BUDGET_BASELINE.json          jev-opt/experiments/budget_report.py (Jev pipeline 3-seed mean per set)
  results/budget_baseline/ft/<set>.json training seconds of the fine-tuned encoders (whole grid, all seeds)
  runs/jev-opt/v3-<task>-P/run.json     started_at / finished_at of the seed-0 question search of each of the 8
                                        RQ3 configurations (the same runs as the $1.66 search cost, \\frCostFqMedian)

"Reaches the paper's method" uses the paper's 0.5-point rule (sections/setup.tex): score >= paper - 0.005.

Run from the repo root:  uv run scripts/paper_lora.py [--out DIR]   # DIR replaces paper/generated
"""

from __future__ import annotations

import json
import statistics
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_tables as pt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "paper" / "generated"
TOL = 0.005
SEARCH_TASKS = ["contempo-tbdense", "ezstance-subtaskA", "smarter-implicit-hate", "edit-intent", "inli",
                "dress-new-content", "dress-new-organization", "dress-new-language"]
WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]


def signed(x: float) -> str:
    v = round(100 * x, 1)
    return f"{'+' if v > 0 else ('-' if v < 0 else '')}{abs(v):.1f}"


def listing(names: list[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def tnum(x: float, sign: bool = False) -> str:
    s = signed(x) if sign else f"{100 * x:.1f}"
    return s.replace("-", "$-$")


def table(rows: list[dict]) -> str:
    def diff(c: dict) -> str:
        star = "$^\\ast$" if c["p_holm"] < 0.05 else ""
        return f"{tnum(c['delta'], True)}{star} {{\\tiny({tnum(c['ci'][0], True)}, {tnum(c['ci'][1], True)})}}"
    L = ["% Generated by scripts/paper_lora.py from results/H100_LORA.json. Do not edit.",
         "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
         "\\begin{tabular}{@{}lcccccccccc@{}}", "\\toprule",
         "& \\multicolumn{2}{c}{LoRA} & \\multicolumn{2}{c}{Qwen, opt.\\ q.\\ + LR} & \\multicolumn{2}{c}{Best baseline}"
         " & \\multicolumn{2}{c}{\\jev{} pipeline} & & \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}",
         "\\multirow{-2}{*}[0.5ex]{Set} & " + " & ".join(f"\\multicolumn{{1}}{{c}}{{{h}}}" for h in ("Score", "lr") + ("Score", "LoRA $-$ (95\\% CI)") * 3
                                                     + ("\\multirow{-2}{*}[0.5ex]{Paper}", "\\multirow{-2}{*}[0.5ex]{GPU-h}"))
         + " \\\\", "\\midrule"]
    for r in rows:
        c = r["contrasts"]
        L.append(f"{pt.CONFIG_LABEL[r['set']]} & {tnum(r['lora'])} & {r['chosen_lr']:.0e} & {tnum(r['optimized'])} & {diff(c['lora-opt'])} & "
                 f"{tnum(r['encoder']['best_score'])} ({r['encoder']['best']}) & {diff(c['lora-enc'])} & {tnum(r['jev'])} & "
                 f"{diff(c['lora-jev'])} & {tnum(r['paper'])} & {r['gpu_hours']:.1f} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(L).replace("e-04", "e$-$4") + "\n"


def main() -> None:
    rd = lambda p: json.loads((ROOT / p).read_text())
    lo = rd("results/H100_LORA.json")
    assert lo["status"] == "finished", lo["status"]
    bb = rd("results/BUDGET_BASELINE.json")["sets"]
    rows, s = lo["sets"], lo["summary"]
    m: list[tuple[str, str]] = [("lrNSets", str(len(rows))), ("lrNSeeds", str(len(rows[0]["lora_seeds"])))]

    for key, tag in (("lora-jev", "Jev"), ("lora-opt", "Opt"), ("lora-enc", "Enc")):
        x = s[key]
        m += [(f"lrPool{tag}", signed(x["pooled_delta"])), (f"lrPool{tag}Lo", signed(x["pooled_ci"][0])),
              (f"lrPool{tag}Hi", signed(x["pooled_ci"][1])), (f"lrAhead{tag}", str(x["n_holm_positive"])),
              (f"lrBehind{tag}", str(x["n_holm_negative"])), (f"lrPos{tag}", str(x["n_positive"]))]
    g = s["gap"]
    m += [("lrGap", f"{100 * g['lora']['all']:.0f}"), ("lrGapCfg", f"{100 * g['lora']['cfg8']:.0f}"),
          ("lrGapFrozen", f"{100 * g['lora']['frozen5']:.0f}"), ("lrGapQwenOpt", f"{100 * g['opt']['all']:.0f}")]

    reach = [r["set"] for r in rows if r["lora"] >= r["paper"] - TOL]
    jev_reach = [r["set"] for r in rows if bb[r["set"]]["jev"]["mean"] >= r["paper"] - TOL]
    m += [("lrNReach", str(len(reach))), ("lrNReachWord", WORDS[len(reach)] if len(reach) < 10 else str(len(reach))),
          ("lrReachSets", listing([pt.CONFIG_LABEL[x] for x in reach])),
          ("lrJevNReach", str(len(jev_reach))), ("lrJevNReachWord", WORDS[len(jev_reach)] if len(jev_reach) < 10 else str(len(jev_reach))),
          ("lrJevReachSets", listing([pt.CONFIG_LABEL[x] for x in jev_reach]))]

    hours = [r["gpu_hours"] for r in rows]
    m += [("lrGpuHours", f"{s['gpu_hours']:.1f}"), ("lrGpuHoursSetMed", f"{statistics.median(hours):.1f}"),
          ("lrGpuHoursSetMin", f"{min(hours):.1f}"), ("lrGpuHoursSetMax", f"{max(hours):.1f}"),
          ("lrPeakGiB", f"{s['peak_memory_gib']:.1f}")]
    # validation chose the last of the three epochs (the grid's end) on this many configurations
    m += [("lrNLastEpoch", str(sum(all(e == 3 for e in r["epochs"]) for r in rows)))]

    ft = [rd(f"results/budget_baseline/ft/{r['set']}.json")["seconds"] / 3600 for r in rows]
    m += [("efEncGpuHoursSetMed", f"{statistics.median(ft):.2f}")]

    wall = []
    for t in SEARCH_TASKS:
        st = rd(f"runs/jev-opt/v3-{t}-P/run.json")
        assert st["state"] == "finished" and st.get("resumed_at") is None, t
        wall.append((datetime.fromisoformat(st["finished_at"]) - datetime.fromisoformat(st["started_at"])).total_seconds() / 60)
    m += [("efSearchMinutesMed", f"{statistics.median(wall):.0f}"), ("efSearchMinutesMin", f"{min(wall):.0f}"),
          ("efSearchMinutesMax", f"{max(wall):.0f}"), ("efSearchN", str(len(wall)))]

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "lora.tex").write_text("% Generated by scripts/paper_lora.py (LoRA fine-tuning, effort). Do not edit.\n"
                                  + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m))
    (OUT / "app_lora.tex").write_text(table(rows))
    for k, v in m:
        print(f"{k} = {v}")


if __name__ == "__main__":
    main()
