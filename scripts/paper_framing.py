"""Framing numbers of the paper (three research questions) -> results/framing.json, results/FRAMING.md,
paper/generated/framing.tex (macros only).

Assembles, without recomputing anything, the saved outputs of:
  results/framing_audit_ci.json     scripts/framing_audit_ci.py (RQ1: zero-shot audit vs published numbers)
  results/framing_features.json     jev-opt/experiments/framing_features.py (RQ3: questions as features, drop-aux)
  results/framing_ablation.json     jev-opt/experiments/framing_ablation.py (RQ3: A vs P, readout alone, cost)
  results/framing_conventions.json  scripts/framing_conventions.py (RQ2/RQ3: conventions stated by winning programs)

Run from the repo root:  uv run scripts/paper_framing.py
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT_TEX = ROOT / "paper" / "generated" / "framing.tex"
OUT_MD = RES / "FRAMING.md"
OUT_JSON = RES / "framing.json"

# study task slug -> (macro suffix, display name)
TASKS = {
    "contempo-tbdense": ("TBDense", "TB-Dense"),
    "ezstance-subtaskA": ("EZStance", "EZ-STANCE A"),
    "smarter-implicit-hate": ("ImplicitHate", "Implicit hate"),
    "edit-intent": ("EditIntent", "Edit intent"),
    "inli": ("INLI", "INLI"),
    "dress-new-content": ("DressContent", "DREsS content"),
    "dress-new-organization": ("DressOrganization", "DREsS organization"),
    "dress-new-language": ("DressLanguage", "DREsS language"),
}
CATS = ("above", "below", "parity", "inconclusive")


def load(name: str) -> dict[str, Any]:
    return json.loads((RES / name).read_text())


def p1(x: float) -> str:
    return f"{100 * x:.1f}"


def sp1(x: float) -> str:
    return f"{100 * x:+.1f}"


def usd(x: float) -> str:
    return f"{x:.2f}"


def tex_escape(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


def median(xs: list[float]) -> float:
    return statistics.median(xs)


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.values: dict[str, str] = {}

    def add(self, name: str, value: Any) -> None:
        assert name.isalpha(), name
        assert name not in self.values, name
        self.values[name] = str(value)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def main() -> None:
    audit = load("framing_audit_ci.json")
    feats = load("framing_features.json")
    abl = load("framing_ablation.json")
    conv = load("framing_conventions.json")
    m = Macros()
    md: list[str] = [
        "# Framing numbers: three research questions", "",
        "Generated by `scripts/paper_framing.py` from `results/framing_audit_ci.json` (`scripts/framing_audit_ci.py`),",
        "`results/framing_features.json` (`jev-opt/experiments/framing_features.py`), `results/framing_ablation.json`",
        "(`jev-opt/experiments/framing_ablation.py`) and `results/framing_conventions.json` (`scripts/framing_conventions.py`).",
        "All analyses are offline: saved predictions and the Jev response cache in cache-only mode (a cache miss raises);",
        "no Jev call was made and no test split was consumed. Values ×100 unless stated.", "",
    ]
    out: dict[str, Any] = {}

    # ---------------------------------------------------------------- RQ1: audit separation
    tasks = audit["tasks"]
    n = len(tasks)
    cnt_p = {c: sum(t["vs_paper"] == c for t in tasks.values()) for c in (*CATS, "not_bootstrappable")}
    llm_rows = [t for t in tasks.values() if t.get("llm") is not None]
    cnt_l = {c: sum(t["vs_llm"] == c for t in llm_rows) for c in CATS}
    margin = audit["margin"]
    m.add("frAuditN", n)
    m.add("frBootB", f"{audit['B']:,}")
    m.add("frParityMargin", f"{100 * margin:g}")
    for c, name in zip(CATS, ("Above", "Below", "Parity", "Inconcl")):
        m.add(f"frSpec{name}", cnt_p[c])
        m.add(f"frLlm{name}", cnt_l[c])
    m.add("frSpecNotBoot", cnt_p["not_bootstrappable"])
    m.add("frLlmN", len(llm_rows))
    # Cross-tab with the audit's outcome groups (scripts/paper_tables.py rows(): 0.5-point tolerance; without an LLM
    # baseline "between" = >= 80% of the task-specific score); checked against \nReplaces/\nBetween/\nFails.
    def group(t: dict[str, Any]) -> str:
        if t["jev"] >= t["paper"] - 0.005:
            return "replaces"
        if t.get("llm") is not None:
            return "between" if t["jev"] >= t["llm"] - 0.005 else "below"
        return "between" if t["jev"] / t["paper"] >= 0.8 else "below"
    groups = {g: [t for t in tasks.values() if group(t) == g] for g in ("replaces", "between", "below")}
    nums = (ROOT / "paper" / "generated" / "numbers.tex").read_text()
    for g, mac in (("replaces", "nReplaces"), ("between", "nBetween"), ("below", "nFails")):
        assert f"\\newcommand{{\\{mac}}}{{{len(groups[g])}}}" in nums, f"{g}: {len(groups[g])} does not match \\{mac} in numbers.tex"
    cross = {g: {c: sum(t["vs_paper"] == c for t in ts) for c in CATS} for g, ts in groups.items()}
    cross_llm = {g: {c: sum(t["vs_llm"] == c for t in ts) for c in (*CATS, "n/a")} for g, ts in groups.items()}
    for g, gname in (("replaces", "Rep"), ("between", "Bet"), ("below", "Fail")):
        for c, name in zip(CATS, ("Above", "Below", "Parity", "Inconcl")):
            m.add(f"fr{gname}Spec{name}", cross[g][c])
            m.add(f"fr{gname}Llm{name}", cross_llm[g][c])
    out["rq1_audit"] = {"n": n, "vs_paper": cnt_p, "vs_llm": cnt_l, "n_llm": len(llm_rows), "margin": margin, "B": audit["B"],
                        "by_group_vs_paper": cross, "by_group_vs_llm": cross_llm}
    md += ["## RQ1: zero-shot audit, separated / parity / inconclusive", "",
           f"Per comparable test set ({n}), Jev's zero-shot score is bootstrapped over test units (paired over the units the",
           f"metric is defined over, from the saved predictions; {audit['B']:,} resamples, seed 0, percentile intervals) and",
           "compared with the paper's published point value, which carries no uncertainty. Exclusive categories, in this",
           "precedence: **separated above/below** = the 95% CI excludes the published point; **parity** = the 90% CI lies",
           f"within the published value ±{100 * margin:g} points (margin chosen post hoc, as Rao & Callison-Burch 2026 do);",
           "**inconclusive** = neither. Margin applied on each metric's stored scale.", "",
           "| Comparison | n | Separated above | Separated below | Parity | Inconclusive |", "|---|---:|---:|---:|---:|---:|",
           f"| vs task-specific method | {n} | {cnt_p['above']} | {cnt_p['below']} | {cnt_p['parity']} | {cnt_p['inconclusive']} |",
           f"| vs prompted-LLM baseline | {len(llm_rows)} | {cnt_l['above']} | {cnt_l['below']} | {cnt_l['parity']} | {cnt_l['inconclusive']} |", "",
           "By the audit's outcome groups (Table main: matches/beats the task-specific method within 0.5 points, between the",
           "LLM baseline and the method, below both):", "",
           "| Audit group | n | vs task-specific: above / below / parity / inconclusive | vs LLM: above / below / parity / inconclusive / no LLM number |",
           "|---|---:|---|---|"]
    for g in ("replaces", "between", "below"):
        a, b = cross[g], cross_llm[g]
        md.append(f"| {g} | {len(groups[g])} | {a['above']} / {a['below']} / {a['parity']} / {a['inconclusive']} | "
                  f"{b['above']} / {b['below']} / {b['parity']} / {b['inconclusive']} / {b['n/a']} |")
    outside = [t["name"].replace("\\ ", " ") for t in tasks.values() if t.get("ci90") and not t["ci90"][0] <= t["jev"] <= t["ci90"][1]]
    md += ["", "Percentile intervals of metrics averaged over many labels or groups can be skewed away from the point estimate "
           "(a resample drops rare labels); test sets whose point estimate lies outside their own 90% interval: "
           f"{', '.join(outside) if outside else 'none'}.", ""]
    if cnt_p["not_bootstrappable"]:
        md += [f"Not bootstrappable: {cnt_p['not_bootstrappable']} (listed below).", ""]
    md += ["| Test set | Metric | Unit (n) | Jev | 95% CI | 90% CI | Task-specific | vs task-specific | LLM | vs LLM |",
           "|---|---|---|---:|---|---|---:|---|---:|---|"]
    for t in tasks.values():
        ci95 = f"{p1(t['ci95'][0])}–{p1(t['ci95'][1])}" if t.get("ci95") else "–"
        ci90 = f"{p1(t['ci90'][0])}–{p1(t['ci90'][1])}" if t.get("ci90") else "–"
        llm = "–" if t.get("llm") is None else p1(t["llm"])
        md.append(f"| {t['name'].replace(chr(92) + ' ', ' ')} | {t['metric']} | {t['unit']} ({t['n_units']:,}) | {p1(t['jev'])} | {ci95} | {ci90} | "
                  f"{p1(t['paper'])} | {t['vs_paper']} | {llm} | {t['vs_llm']} |")
    md.append("")

    # ---------------------------------------------------------------- RQ3: questions as features
    ft = feats["tasks"]
    ev = {s: ft[s]["evidence_share_mean"] for s in TASKS}
    for s, (suf, _) in TASKS.items():
        m.add(f"frEvid{suf}", p1(ev[s]))
        m.add(f"frEvidAudit{suf}", p1(ft[s]["evidence_share_vs_audit_mean"]))
    m.add("frEvidMedian", p1(median(list(ev.values()))))
    m.add("frEvidMin", p1(min(ev.values())))
    m.add("frEvidMax", p1(max(ev.values())))
    eva = [ft[s]["evidence_share_vs_audit_mean"] for s in TASKS]
    m.add("frEvidAuditMedian", p1(median(eva)))
    ac = feats["anatomy_counts"]
    m.add("frProgTotal", ac["total"])
    m.add("frProgAux", ac["aux"])
    m.add("frProgType", ac["type_differs"])
    m.add("frProgOvr", ac["one_vs_rest"])
    m.add("frProgStacked", ac["stacked"])
    m.add("frProgDemos", ac["demos"])
    progs = [(s, k, r) for s in TASKS for k, r in ft[s]["seeds"].items()]
    m.add("frProgNoLabel", sum(r["main_names_no_label"] for _, _, r in progs))
    md += ["## RQ3: questions as features (test, all 3 seeds)", "",
           "Per chosen program (8 tasks × optimizer seeds 0/1/2, `results/seeds.json` selection), re-executed on test from",
           "the cache and checked against the score recorded at consumption. **Evidence share** = share of test items where the",
           "method's prediction is correct while Jev's top answer on the program's main question (the question carrying the",
           "readout) is not the gold label: the readout reads the label off the answers rather than taking Jev's answer. Top",
           "answer = argmax option (Choice), argmax Noul (one-vs-rest), argmax level mapped to the label (Score; DREsS: the",
           "argmax level differs from gold), none for a Noul main question that names no label. *Lost* = the converse (main",
           "top answer right, method wrong). *vs audit* = the same with the audit question's zero-shot test prediction",
           "(the paper's own question, `study-<task>-zero`) in place of the main question's top answer. Per-item correctness",
           "is descriptive (the primary metrics are F1/QWK).", "",
           "| Task | Seed | Test | Acc. method | Acc. main top | Evidence | Lost | Evidence vs audit | Lost vs audit | Aux | Type ≠ paper | 1-vs-rest | Stacked |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|---|"]
    yn = lambda b: "yes" if b else "–"  # noqa: E731
    for s, k, r in progs:
        a = r["anatomy"]
        note = " (main: Noul, no label)" if r["main_names_no_label"] else ""
        md.append(f"| {TASKS[s][1]} | {k} | {p1(r['test'])} | {p1(r['acc_method'])} | {p1(r['acc_main_top'])}{note} | {p1(r['evidence_share'])} | "
                  f"{p1(r['lost_share'])} | {p1(r['evidence_share_vs_audit'])} | {p1(r['lost_share_vs_audit'])} | "
                  f"{yn(a['aux'])}{' (%d)' % a['n_aux'] if a['aux'] else ''} | {yn(a['type_differs'])} | {yn(a['one_vs_rest'])} | {yn(a['stacked'])} |")
    md += ["", "| Task | Evidence share, 3-seed mean | Evidence vs audit, mean | Lost, mean |", "|---|---:|---:|---:|"]
    for s in TASKS:
        md.append(f"| {TASKS[s][1]} | {p1(ev[s])} | {p1(ft[s]['evidence_share_vs_audit_mean'])} | {p1(ft[s]['lost_share_mean'])} |")
    md += ["", f"Program anatomy over {ac['total']} programs: auxiliary questions {ac['aux']}, main-question type different from the "
           f"paper's {ac['type_differs']}, one-vs-rest Noul questions {ac['one_vs_rest']}, stacked variants {ac['stacked']}, "
           f"kNN demonstrations {ac['demos']}.", ""]
    nolabel = [f"{TASKS[s][1]} seed {k}" for s, k, r in progs if r["main_names_no_label"]]
    if nolabel:
        md += [f"Main question naming no label ({', '.join(nolabel)}): its top answer is never the gold label, so every correct item "
               "counts as evidence; this raises that task's 3-seed mean. The *vs audit* column has no such case.", ""]
    out["rq3_features"] = {"evidence_share_mean": ev, "evidence_share_vs_audit_mean": dict(zip(TASKS, eva)), "anatomy_counts": ac}

    # drop-aux
    drops = [(s, k, r) for s, k, r in progs if "drop_aux" in r]
    dv = [r["drop_aux"]["val"]["delta"] for _, _, r in drops]
    dt = [r["drop_aux"]["test"]["delta"] for _, _, r in drops]
    m.add("frDropAuxN", len(drops))
    m.add("frDropAuxValMedian", sp1(median(dv)))
    m.add("frDropAuxTestMedian", sp1(median(dt)))
    m.add("frDropAuxValWorse", sum(d < 0 for d in dv))
    m.add("frDropAuxTestWorse", sum(d < 0 for d in dt))
    m.add("frDropAuxValSig", sum(r["drop_aux"]["val"]["ci"][1] < 0 for _, _, r in drops))
    m.add("frDropAuxTestSig", sum(r["drop_aux"]["test"]["ci"][1] < 0 for _, _, r in drops))
    m.add("frDropAuxValMin", sp1(min(dv)))
    m.add("frDropAuxValMax", sp1(max(dv)))
    md += ["### Dropping the auxiliary questions (post hoc)", "",
           "Programs with auxiliary questions: the auxiliary questions removed from the readout, the readout refit on the run's",
           "400-example train fit slice exactly as the run fit it (cached answers, no new calls), scored on val and test. Δ = without",
           "aux − with aux (negative: the auxiliary questions help), paired bootstrap 95% CI (2,000 resamples, seed 0). Refit check:",
           "agreement of the refit full program's predictions with the recorded ones (validates the refit procedure).", "",
           "| Task | Seed | Dropped | Val with → without (Δ, 95% CI) | Test with → without (Δ, 95% CI) | Refit check val / test |",
           "|---|---:|---|---|---|---|"]
    for s, k, r in drops:
        d = r["drop_aux"]
        f = lambda x: f"{p1(x['a'])} → {p1(x['b'])} ({sp1(x['delta'])}, {sp1(x['ci'][0])}…{sp1(x['ci'][1])})"  # noqa: E731
        nodes = ", ".join("`%s`" % x for x in d["dropped_nodes"])
        md.append(f"| {TASKS[s][1]} | {k} | {nodes} | {f(d['val'])} | {f(d['test'])} | "
                  f"{p1(d['refit_check']['val_agree'])}% / {p1(d['refit_check']['test_agree'])}% |")
    md += ["", f"Summary: {len(drops)} programs; median Δ val {sp1(median(dv))}, median Δ test {sp1(median(dt))}; val worse without aux in "
           f"{sum(d < 0 for d in dv)}, test worse in {sum(d < 0 for d in dt)}.", ""]
    out["rq3_drop_aux"] = {"n": len(drops), "val_deltas": dv, "test_deltas": dt, "val_median": median(dv), "test_median": median(dt)}

    # ---------------------------------------------------------------- RQ3: ablation (evidence, not the question)
    ab = abl["ablation"]
    dd = {s: ab[s]["delta"] for s in TASKS}
    for s, (suf, _) in TASKS.items():
        m.add(f"frAblA{suf}", p1(ab[s]["A"]))
        m.add(f"frAblP{suf}", p1(ab[s]["P"]))
        m.add(f"frAblD{suf}", sp1(ab[s]["delta"]))
        m.add(f"frAblDLo{suf}", sp1(ab[s]["ci"][0]))
        m.add(f"frAblDHi{suf}", sp1(ab[s]["ci"][1]))
    m.add("frAblDMin", sp1(min(dd.values())))
    m.add("frAblDMax", sp1(max(dd.values())))
    m.add("frAblDMedian", sp1(median(list(dd.values()))))
    m.add("frAblNPos", sum(d > 0 for d in dd.values()))
    m.add("frAblNCIPos", sum(ab[s]["ci"][0] > 0 for s in TASKS))
    m.add("frAblNTasks", len(TASKS))
    md += ["## RQ3 ablation: rewriting the question with the readout held fixed (val)", "",
           "A = the paper's question + fitted readout (`v3-<task>-A`); P = feature-question search (`v3-<task>-P` top-single,",
           "seed 0: rewritten questions + fitted readout, the same readout family and fit slice). Validation split; Δ = P − A with",
           "a paired bootstrap 95% CI over val examples (2,000 resamples, seed 0). P is optimistically biased by val selection",
           "among ≤ 4 candidates.", "",
           "| Task | Metric | n val | A | P | Δ (95% CI) |", "|---|---|---:|---:|---:|---|"]
    for s in TASKS:
        a = ab[s]
        md.append(f"| {TASKS[s][1]} | {a['metric']} | {a['n_val']:,} | {p1(a['A'])} | {p1(a['P'])} | {sp1(a['delta'])} ({sp1(a['ci'][0])}…{sp1(a['ci'][1])}) |")
    thin = [f"{TASKS[s][1]} (lower bound {100 * ab[s]['ci'][0]:+.3f})" for s in TASKS if 0 < ab[s]["ci"][0] < 0.0005]
    md += ([f"Lower bound above 0 but rounding to +0.0: {', '.join(thin)}.", ""] if thin else [""])
    ro = abl["readout_alone"]
    md += ["### Readout alone on test", "",
           "Readout alone = the audit question's unchanged zero-shot answers + a fitted readout (`results/heads.json`, pre-registered,",
           "tested once); method = feature-question search, 3-seed test mean ± sd (`results/seeds.json`). Available for two tasks.", "",
           "| Task | Audit zero-shot | Readout alone | Method (mean ± sd) | Method per seed |", "|---|---:|---:|---:|---|"]
    for s, r in ro.items():
        suf = TASKS[s][0]
        m.add(f"frRo{suf}", p1(r["readout_alone"]))
        m.add(f"frRoZero{suf}", p1(r["readout_alone_zero_shot"]))
        m.add(f"frMethod{suf}", p1(r["method_mean"]))
        m.add(f"frMethodSd{suf}", p1(r["method_sd"]))
        md.append(f"| {TASKS[s][1]} | {p1(r['readout_alone_zero_shot'])} | {p1(r['readout_alone'])} | {p1(r['method_mean'])} ± {p1(r['method_sd'])} | "
                  f"{', '.join(p1(x) for x in r['method_seeds'])} |")
    md.append("")
    out["rq3_ablation"] = {"deltas": dd, "readout_alone": ro}

    # ---------------------------------------------------------------- conventions
    progs_c = conv["programs"]
    m.add("frConvN", conv["count"])
    m.add("frConvTotal", conv["total"])
    m.add("frConvTasks", conv["tasks_with_convention"])
    m.add("frConvJudgeAgree", conv["judge_agreement"])
    for letter, ex in zip("ABC", conv["examples"]):
        m.add(f"frConvQuote{letter}", tex_escape(ex["quote"]))
        m.add(f"frConvQuote{letter}Task", TASKS[ex["task"]][1])
    md += ["## Conventions stated by the winning programs", "",
           "Rubric (fixed in `scripts/framing_conventions.py`):", "", "> " + conv["rubric"].replace("\n", "\n> "), "",
           f"Judge: {conv['judge_model']}; a second reading of every program against its seed gives the final verdict. "
           f"**{conv['count']} of {conv['total']}** programs state a dataset convention absent from the paper's question "
           f"({conv['tasks_with_convention']} of 8 tasks); judge and final verdict agree on {conv['judge_agreement']}/{conv['total']}.", "",
           "| Task | Seed | Candidate | Judge | Final | Verbatim convention | Note |", "|---|---:|---|---|---|---|---|"]
    for p in progs_c:
        q = p["quote"].replace("|", "\\|")
        md.append(f"| {TASKS[p['task']][1]} | {p['seed']} | {p['candidate']} | {yn(p['judge']['convention'])} | {yn(p['final_verdict'])} | "
                  f"{'“' + q + '”' if q else ''} | {p['note'].replace('|', '/')} |")
    md += ["", "Examples:", ""] + [f"- {TASKS[e['task']][1]} (seed {e['seed']}): “{e['quote']}” — {e['rule']}" for e in conv["examples"]] + [""]
    out["conventions"] = {"count": conv["count"], "total": conv["total"], "tasks": conv["tasks_with_convention"], "examples": conv["examples"]}

    # ---------------------------------------------------------------- cost
    co = abl["cost"]
    keys = {"fqs": "Fq", "gepa_text": "GepaText", "gepa_program": "GepaProgram"}
    for s, (suf, _) in TASKS.items():
        for k, name in keys.items():
            m.add(f"frCost{name}{suf}", usd(co[s][k]["total"]))
        m.add(f"frCostFqSeedMean{suf}", usd(co[s]["fqs_seed_mean_total"]))
    for k, name in keys.items():
        vals = [co[s][k]["total"] for s in TASKS]
        m.add(f"frCost{name}Median", usd(median(vals)))
        m.add(f"frCost{name}Total", usd(sum(vals)))
    ratio_t = [co[s]["fqs"]["total"] / co[s]["gepa_text"]["total"] for s in TASKS]
    ratio_p = [co[s]["fqs"]["total"] / co[s]["gepa_program"]["total"] for s in TASKS]
    m.add("frCostRatioTextMedian", f"{median(ratio_t):.2f}")
    m.add("frCostRatioProgramMedian", f"{median(ratio_p):.2f}")
    md += ["## Optimization cost per task (Jev + optimizer, $)", "",
           "Optimization only (no test). Jev used = Jev-reported cost of the distinct train/val requests in the run's saved",
           "response ledger (requests served from the shared cache count; the definition of tab:opt-cost); optimizer = omp spend",
           "(`usage.jsonl`). Feature-question search = `v3-<task>-P` (seed 0; seeds 1/2 in the mean column); GEPA text / program",
           "search = the v1 study runs `study-<task>-{text,program}`.", "",
           "| Task | FQS Jev | FQS opt. | **FQS total** | FQS 3-seed mean total | GEPA text Jev | GEPA text opt. | **GEPA text total** | "
           "GEPA program Jev | GEPA program opt. | **GEPA program total** | FQS wall h | GEPA text / program wall h |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    wh = lambda x: "–" if x is None else f"{x:.2f}"  # noqa: E731
    for s in TASKS:
        c = co[s]
        md.append(f"| {TASKS[s][1]} | {usd(c['fqs']['jev_used'])} | {usd(c['fqs']['omp'])} | **{usd(c['fqs']['total'])}** | "
                  f"{usd(c['fqs_seed_mean_total'])} | {usd(c['gepa_text']['jev_used'])} | {usd(c['gepa_text']['omp'])} | "
                  f"**{usd(c['gepa_text']['total'])}** | {usd(c['gepa_program']['jev_used'])} | {usd(c['gepa_program']['omp'])} | "
                  f"**{usd(c['gepa_program']['total'])}** | {wh(c['fqs']['wall_h'])} | {wh(c['gepa_text']['wall_h'])} / {wh(c['gepa_program']['wall_h'])} |")
    tot = {k: sum(co[s][k]["total"] for s in TASKS) for k in keys}
