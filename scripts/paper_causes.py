"""Paper macros and appendix table for the cause table (LLM draft, checked by an author).

Reads results/causes.json (scripts/cause_table.py) and writes paper/generated/causes.tex (\\cs* count macros) and
paper/generated/app_causes.tex (Table tab:causes, with the evidence; extended appendix) and
paper/generated/app_causes_compact.tex (the same rows, one line each, no evidence; appendix of the paper). Run from the repo root after scripts/cause_table.py:

    uv run scripts/paper_causes.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_tables as pt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "generated"
SRC = ROOT / "results" / "causes.json"

NAME = {"conv": "Conv", "large": "Large", "coarse": "Coarse", "other": "Other"}
SHORT = {"conv": "conv.", "large": "large", "coarse": "coarse", "other": "other"}
TITLE = {"conv": "(a) Unstated annotation conventions", "large": "(b) Very large or opaque label space",
         "coarse": "(c) Probabilities too coarse for the paper's method", "other": "(d) Other or unclear"}


def tex(s: str) -> str:
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")):
        s = s.replace(a, b)
    s = s.replace("->", "$\\to$").replace(">=", "$\\geq$")
    s = re.sub(r"\bqhat\b", "$\\\\hat q$", s)
    s = re.sub(r"\brho\b", "$\\\\rho$", s)
    s = re.sub(r"\balpha\b", "$\\\\alpha$", s)
    s = re.sub(r"\bP=0\b", "$P=0$", s)
    return s


def macros(d: dict) -> str:
    a = d["agreement"]
    lines = ["% Generated by scripts/paper_causes.py from results/causes.json. Do not edit.",
             f"\\newcommand{{\\csN}}{{{d['n_sets']}}}", f"\\newcommand{{\\csNPapers}}{{{d['n_papers']}}}",
             f"\\newcommand{{\\csNChanged}}{{{d['n_changed']}}}", f"\\newcommand{{\\csAgree}}{{{a['agree']}}}",
             f"\\newcommand{{\\csKappa}}{{{a['kappa']:.2f}}}", f"\\newcommand{{\\csKappaLo}}{{{a['kappa_ci'][0]:.2f}}}",
             f"\\newcommand{{\\csKappaHi}}{{{a['kappa_ci'][1]:.2f}}}"]
    for c, name in NAME.items():
        lines.append(f"\\newcommand{{\\cs{name}}}{{{d['counts'][c]}}}")
        lines.append(f"\\newcommand{{\\cs{name}Papers}}{{{d['paper_counts'][c]}}}")
        for k in ("high", "medium", "low"):
            lines.append(f"\\newcommand{{\\cs{name}{k.capitalize()}}}{{{d['by_confidence'][c][k]}}}")
        lines.append(f"\\newcommand{{\\cs{name}Secondary}}{{{d['secondary_counts'][c]}}}")
    for k in ("high", "medium", "low"):
        n = sum(s["confidence"] == k for s in d["sets"])
        lines.append(f"\\newcommand{{\\csN{k.capitalize()}}}{{{n}}}")
    return "\n".join(lines) + "\n"


def table(d: dict) -> str:
    lines = ["% Generated by scripts/paper_causes.py from results/causes.json. Do not edit.",
             "\\begin{table*}[p]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\renewcommand{\\arraystretch}{1.05}",
             "\\begin{tabular}{@{}l r l l p{10.5cm}@{}}", "\\toprule",
             "Test set & Gap & Sec. & Conf. & Evidence (sources in \\texttt{results/CAUSES.md}) \\\\"]
    for c in NAME:
        members = [s for s in d["sets"] if s["primary"] == c]
        if not members:
            continue
        lines += ["\\midrule",
                  f"\\multicolumn{{5}}{{@{{}}l}}{{\\textbf{{\\textit{{{TITLE[c]}}}}}: {len(members)} sets, "
                  f"{d['paper_counts'][c]} papers}} \\\\"]
        for s in members:
            sec = SHORT[s["secondary"]] if s["secondary"] else "--"
            gap = s["gap"]
            gcell = f"$-${-gap:.1f}" if gap < 0 else f"{gap:.1f}"
            lines.append(f"{pt.name_cell(pt.SET_LABEL[s['set']], '')} & {gcell} & {sec} & {s['confidence']} & {tex(s['evidence'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              f"\\caption{{Cause assignment for the {d['n_sets']} zero-shot shortfall sets (not matching or "
              "beating the task-specific method), grouped by primary cause, under the rule of "
              "Appendix~\\ref{app:causes}. An LLM drafted every row and an author checked it. Gap: \\jev{} minus "
              "the task-specific method, in points (Table~\\ref{tab:full}). Sec.: secondary cause. Conf.: the draft's "
              "confidence in the primary cause, or \\emph{author} where the author changed it (the evidence is then the "
              "draft's). Counts in the group rows are of primary causes. A paper counts toward every cause one of its "
              "sets has.}",
              "\\label{tab:causes}", "\\end{table*}", ""]
    return "\n".join(lines)


def compact_table(d: dict) -> str:
    lines = ["% Generated by scripts/paper_causes.py from results/causes.json. Do not edit.",
             "\\begin{table}[!tp]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{@{}lccc@{}}", "\\toprule", "Test set & \\multicolumn{1}{c}{Gap} & \\multicolumn{1}{c}{Sec.} & \\multicolumn{1}{c}{Conf.} \\\\"]
    for c in NAME:
        members = [s for s in d["sets"] if s["primary"] == c]
        if not members:
            continue
        lines += ["\\midrule", f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{{TITLE[c]}}}: {len(members)} sets, "
                  f"{d['paper_counts'][c]} papers}} \\\\"]
        for s in members:
            sec = SHORT[s["secondary"]] if s["secondary"] else "--"
            gap = s["gap"]
            gcell = f"$-${-gap:.1f}" if gap < 0 else f"{gap:.1f}"
            lines.append(f"{pt.name_cell(pt.SET_LABEL[s['set']], '')} & {gcell} & {sec} & {s['confidence']} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              f"\\caption{{Primary and secondary cause of each of the {d['n_sets']} zero-shot shortfalls, drafted by an LLM "
              "and checked by an author. Gap is \\jev{} minus the paper's method, in points.}",
              "\\label{tab:causes}", "\\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    d = json.loads(SRC.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "causes.tex").write_text(macros(d))
    (OUT / "app_causes.tex").write_text(table(d))
    (OUT / "app_causes_compact.tex").write_text(compact_table(d))


if __name__ == "__main__":
    main()
