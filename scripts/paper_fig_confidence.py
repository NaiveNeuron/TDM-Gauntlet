def bad(x: Any) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def pct(x: float | None, d: int = 1) -> str:
    return "--" if bad(x) else f"{100 * x:.{d}f}"


def num(x: float | None, d: int = 2) -> str:
    return "--" if bad(x) else f"{x:.{d}f}"


def ci_s(c: list[float] | None, d: int = 2, scale: float = 1.0) -> str:
    if c is None or any(bad(x) for x in c):
        return "[--]"
    return f"[{c[0] * scale:.{d}f}, {c[1] * scale:.{d}f}]"


def tex_signed(x: float | None, d: int) -> str:
    return "--" if bad(x) else f"{x:+.{d}f}".replace("-", "$-$")


def p_tex(p: float | None) -> str:
    return "--" if bad(p) else ("$<$0.001" if p < 0.001 else f"{p:.3f}")


def p_md(p: float | None) -> str:
    return "--" if bad(p) else ("<0.001" if p < 0.001 else f"{p:.3f}")


def tag_of(k: str) -> str:
    return "".join(w.capitalize() for w in k.replace("/", " ").replace("_", " ").split()).translate(DIGITS)


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = ["% Generated by scripts/paper_fig_confidence.py from results/confidence.json. Do not edit."]
        self.names: set[str] = set()

    def add(self, name: str, value: Any) -> None:
        assert name.isalpha() and name.startswith("cf"), name
        assert name not in self.names, name
        self.names.add(name)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


