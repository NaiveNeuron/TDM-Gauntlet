    for name, key, color, ls, dy in (("zero-shot", "zero_shot_bands", "#c92a2a", "-", 3),
                                     ("zero-shot + TS", "temperature_scaled_bands", "#e8a33d", "--", None),
                                     ("optimized\nquestions", "readout_bands_pooled_seeds", "#1971c2", "-", -8)):
        num_, den, allu = [0.0] * 4, [0.0] * 4, [0.0] * 4
        for t in tasks.values():
            tot = sum(b["n"] for b in t[key])
            for i, b in enumerate(t[key]):
                allu[i] += b["n"] / tot
                if b["error_rate"] is not None:
                    num_[i] += b["errors"] / tot
                    den[i] += b["n"] / tot
        y = [num_[i] / den[i] if den[i] else float("nan") for i in range(4)]
        share = [d / len(tasks) for d in allu]
        axes[1].plot(x, y, marker="o", ms=2.5, lw=1.0, ls=ls, color=color, label=name)
        for i in range(4):
            if den[i] and dy is not None:
                txt = f"{100 * share[i]:.0f}%" if share[i] >= 0.005 else "<1%"
                if dy > 0:
                    axes[1].annotate(txt, (i, y[i]), textcoords="offset points", xytext=(0, dy), ha="center", fontsize=6, color=color)
