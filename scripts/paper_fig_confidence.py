                    axes[1].annotate(txt, (i, y[i]), textcoords="offset points", xytext=(-3, -3), ha="right", va="top", fontsize=6,
                                     color=color, bbox=dict(boxstyle="square,pad=0.05", fc="white", ec="none", alpha=0.85))
