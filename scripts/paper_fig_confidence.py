def group_row(label: str, g: dict) -> str:
    br = g["band_error_rate"]
    pap = lambda k: (" ⟨" + ci_s(g[f"{k}_ci_papers"])[1:-1] + "⟩") if g.get(f"{k}_ci_papers") else ""  # noqa: E731
    papt = (" ⟨" + ci_s(g["top_band_error_rate_ci_papers"], 1, 100)[1:-1] + "⟩") if g.get("top_band_error_rate_ci_papers") else ""
    return (f"| {label} | {g['n_sets']} / {g['n_papers']} | {pct(g['accuracy_mean'])} | {num(g['auroc_mean'])} {ci_s(g['auroc_mean_ci'])}{pap('auroc_mean')} | "
            f"{num(g['ece_mean'], 3)} ({g['ece_n_sets']}) {ci_s(g['ece_mean_ci'], 3)}{pap('ece_mean').replace(', ', ', ')} | "
            f"{num(g['brier_mean'], 3)} ({g['brier_n_sets']}) | {num(g['augrc_mean'], 3)} {ci_s(g['augrc_mean_ci'], 3)} | {num(g['eaurc_mean'], 3)} | "
            + " | ".join(pct(x) for x in br[:3])
            + f" | {pct(br[3])} {ci_s(g['band_error_rate_ci'][3], 1, 100)}{papt} | {pct(g['band_unit_share'][3])} | "
            f"{pct(g['confident_error_share'])} |")


def group_macros(m: Macros, tag: str, g: dict) -> None:
    br = g["band_error_rate"]
    c = g["counts"]
    m.add(f"cfN{tag}", g["n_sets"])
    m.add(f"cfNPapers{tag}", g["n_papers"])
    m.add(f"cfAuroc{tag}", num(g["auroc_mean"]))
    m.add(f"cfAuroc{tag}Lo", num(g["auroc_mean_ci"][0]))
    m.add(f"cfAuroc{tag}Hi", num(g["auroc_mean_ci"][1]))
    m.add(f"cfEce{tag}", num(g["ece_mean"], 3))
    m.add(f"cfEce{tag}Lo", num(g["ece_mean_ci"][0], 3))
    m.add(f"cfEce{tag}Hi", num(g["ece_mean_ci"][1], 3))
    m.add(f"cfEceN{tag}", g["ece_n_sets"])
    m.add(f"cfBrier{tag}", num(g["brier_mean"], 3))
    m.add(f"cfAugrc{tag}", num(g["augrc_mean"], 3))
    m.add(f"cfAugrc{tag}Lo", num(g["augrc_mean_ci"][0], 3))
    m.add(f"cfAugrc{tag}Hi", num(g["augrc_mean_ci"][1], 3))
    m.add(f"cfEaurc{tag}", num(g["eaurc_mean"], 3))
    m.add(f"cfConfErr{tag}", pct(g["confident_error_share"], 0))
    m.add(f"cfConfErr{tag}Lo", pct(g["confident_error_share_ci"][0], 0))
    m.add(f"cfConfErr{tag}Hi", pct(g["confident_error_share_ci"][1], 0))
    m.add(f"cfTopErr{tag}", pct(br[3], 1))
    m.add(f"cfTopErr{tag}Lo", pct(g["band_error_rate_ci"][3][0], 1))
    m.add(f"cfTopErr{tag}Hi", pct(g["band_error_rate_ci"][3][1], 1))
    m.add(f"cfTopShare{tag}", pct(g["band_unit_share"][3], 0))
    for k, mk in (("auroc_mean", "Auroc"), ("ece_mean", "Ece"), ("augrc_mean", "Augrc")):
        cp = g.get(f"{k}_ci_papers")
        d = 2 if k == "auroc_mean" else 3
        m.add(f"cf{mk}{tag}PapLo", num(cp[0], d) if cp else "--")
        m.add(f"cf{mk}{tag}PapHi", num(cp[1], d) if cp else "--")
    cp = g.get("top_band_error_rate_ci_papers")
    m.add(f"cfTopErr{tag}PapLo", pct(cp[0], 1) if cp else "--")
    m.add(f"cfTopErr{tag}PapHi", pct(cp[1], 1) if cp else "--")
    m.add(f"cfNAurocAbove{tag}", c["bh_auroc_gt_half"])
    m.add(f"cfNConfErrMajority{tag}", sum((RES["sets"][s]["confident_error_share"] or 0) > 0.5 for s in g["sets"]))
    m.add(f"cfNTopSafe{tag}", c["bh_top_rate_lt_10pct"])
    m.add(f"cfNTopDefined{tag}", c["top_band_defined"])
    m.add(f"cfNMiscal{tag}", c["bh_miscalibrated"])
    m.add(f"cfNEceLow{tag}", c["ece_defined"] - c["bh_miscalibrated"])


def rq2(m: Macros, md: list[str]) -> None:
    sets, ex, rq = RES["sets"], RES["excluded"], RES["rq2"]
    m.add("cfNSets", len(sets))
    m.add("cfNExcluded", len(ex))
    m.add("cfNUnits", f"{sum(v['n_units'] for v in sets.values()):,}")
    m.add("cfNPapersAll", len({v["paper"] for v in sets.values()}))
    md += ["## RQ2: confidence vs correctness on the zero-shot test sets", "",
           f"{len(sets)} of the 46 comparable sets (from {len({v['paper'] for v in sets.values()})} papers) have item-level "
           f"correctness and confidence; {len(ex)} are excluded:", ""]
    md += [f"- {v['name']} (`{k}`, {v['outcome']}, cause {v['cause']}): {v['reason']}" for k, v in ex.items()]
    md += ["", "### Groups (each set weighted equally)", "",
           "Sets / papers; AUROC of the confidence for correctness (mean); ECE = equal-mass ECE of the predicted option's "
           "probability (mean over the n sets that have one); Brier (mean over the sets with a full vector); AUGRC and E-AURC "
           "(selective risk, lower is better); error rate per confidence band (bands under 20 units omitted per set; units "
           "weighted 1/n_set); share of units in the top band; share of errors in the top band (secondary, base-rate "
           "dependent). Brackets: fixed-set 95% CI (these sets). Angle brackets: paper-level bootstrap CI (tasks like these), "
           "only for groups whose sets come from ≥ 3 papers; groups from 1–2 papers are descriptive.", "",
           "| Group | Sets / papers | Acc. | AUROC [sets] ⟨papers⟩ | ECE (n) [sets] ⟨papers⟩ | Brier (n) | AUGRC [sets] | E-AURC | err [0,.25) | err [.25,.5) | err [.5,.75) | err [.75,1] [sets] ⟨papers⟩ | units in top band | errors in top band |",
           "|---|---|---:|---|---|---|---|---:|---:|---:|---:|---|---:|---:|"]
    for kind, groups in (("by_cause", [c[:3] for c in CAUSES]), ("by_outcome", OUTCOMES), ("by_primitive", PRIMITIVES), ("preregistered", PREREG)):
        for key, label, tag in groups:
            g = rq[kind][key]
            if not g["n_sets"]:
                continue
            md.append(group_row(label + ("" if g["n_papers"] >= 3 else " (descriptive)"), g))
            group_macros(m, tag, g)
        md.append("|  |  |  |  |  |  |  |  |  |  |  |  |  |  |")
    md += ["", "Per-group counts of sets, each property tested per set and Benjamini–Hochberg-controlled at q = 0.05 over "
           "all sets where it is defined: AUROC > 0.5; ECE above its perfect-calibration consistency band (miscalibrated); "
           "top-band error rate < 10% (of sets whose top band holds ≥ 20 units).", "",
           "| Group | Sets | AUROC > 0.5 | miscalibrated / with probability | top-band error < 10% / defined |", "|---|---:|---:|---:|---:|"]
    for kind, groups in (("by_cause", [c[:3] for c in CAUSES]), ("by_outcome", OUTCOMES), ("by_primitive", PRIMITIVES)):
        for key, label, _ in groups:
            g = rq[kind][key]
            if g["n_sets"]:
                c = g["counts"]
                md.append(f"| {label} | {g['n_sets']} | {c['bh_auroc_gt_half']} | {c['bh_miscalibrated']}/{c['ece_defined']} | "
                          f"{c['bh_top_rate_lt_10pct']}/{c['top_band_defined']} |")
    md += ["", "### Pre-specified group tests (paper-level bootstrap, Holm over the 12 tests)", "",
           "| Comparison | AUROC | ECE | top-band error rate | AUGRC |", "|---|---|---|---|---|"]

    def cell(d: dict, scale: float, digits: int) -> str:
        star = "*" if d["significant_holm"] else ""
        return (f"{scale * d['delta']:+.{digits}f} ⟨{ci_s(d['ci_papers'], digits, scale)[1:-1]}⟩ "
                f"[{ci_s(d['ci_fixed_sets'], digits, scale)[1:-1]}] p={p_md(d['p_holm'])}{star}")
    for name, d in rq["tests"].items():
        md.append(f"| {name} | {cell(d['auroc'], 1, 3)} | {cell(d['ece'], 1, 3)} | {cell(d['top_rate'], 100, 1)} | {cell(d['augrc'], 1, 3)} |")
    md += ["", "⟨paper-level CI⟩ [fixed-set CI]; p Holm-adjusted; \\* p < 0.05. A paper with sets in both groups (EZ-STANCE, "
           "SMARTER, ConTempo) is resampled in each.", "", "Descriptive contrasts (groups from 1–2 papers; fixed-set CI only, no test):", "",
           "| Comparison | AUROC | ECE | top-band error rate | AUGRC |", "|---|---|---|---|---|"]
    for name, d in rq["descriptive_contrasts"].items():
        md.append(f"| {name} | " + " | ".join(f"{(100 if k == 'top_rate' else 1) * d[k]['delta']:+.{1 if k == 'top_rate' else 3}f} "
                                             f"{ci_s(d[k]['ci_fixed_sets'], 1 if k == 'top_rate' else 3, 100 if k == 'top_rate' else 1)}"
                                             for k in ("auroc", "ece", "top_rate", "augrc")) + " |")
    tags = {"matched": "Matched", "opaque": "Opaque", "coarse": "Coarse", "unassigned": "Unassigned"}
    allc = {**{k.removeprefix("conventions_minus_"): v for k, v in rq["tests"].items() if k.startswith("conventions_minus_")},
            **{k.removeprefix("conventions_minus_"): v for k, v in rq["descriptive_contrasts"].items()}}
    conv = rq["by_cause"]["conventions"]
    for other, t in tags.items():
        d = allc[other]
        tested = other in ("matched", "unassigned")
        for stat, mtag, scale, digits in (("auroc", "Auroc", 1, 2), ("top_rate", "TopErr", 100, 1), ("ece", "Ece", 1, 3), ("augrc", "Augrc", 1, 3)):
            c = d[stat]["ci_papers"] if tested else d[stat]["ci_fixed_sets"]
            m.add(f"cfDiff{mtag}Conv{t}", tex_signed(scale * d[stat]["delta"], digits))
            m.add(f"cfDiff{mtag}Conv{t}Lo", tex_signed(scale * c[0], digits))
            m.add(f"cfDiff{mtag}Conv{t}Hi", tex_signed(scale * c[1], digits))
            m.add(f"cfDiff{mtag}Conv{t}PHolm", p_tex(d[stat]["p_holm"]) if tested else "--")
        og = rq["by_cause"][other]
        m.add(f"cfDiffConfErrConv{t}", tex_signed(100 * (conv["confident_error_share"] - og["confident_error_share"]), 0))
        m.add(f"cfDiffConfErrConv{t}Lo", "--")
        m.add(f"cfDiffConfErrConv{t}Hi", "--")
        m.add(f"cfDiffConfErrConv{t}PHolm", "--")
    b = rq["tests"]["below_minus_replaces"]
    for stat, mtag, scale, digits in (("auroc", "Auroc", 1, 2), ("top_rate", "TopErr", 100, 1), ("ece", "Ece", 1, 3), ("augrc", "Augrc", 1, 3)):
        m.add(f"cfDiff{mtag}BelowReplaces", tex_signed(scale * b[stat]["delta"], digits))
        m.add(f"cfDiff{mtag}BelowReplacesLo", tex_signed(scale * b[stat]["ci_papers"][0], digits))
        m.add(f"cfDiff{mtag}BelowReplacesHi", tex_signed(scale * b[stat]["ci_papers"][1], digits))
        m.add(f"cfDiff{mtag}BelowReplacesPHolm", p_tex(b[stat]["p_holm"]))
    m.add("cfNTestsHolm", sum(len(d) for d in rq["tests"].values()))
    m.add("cfNTestsSig", sum(x["significant_holm"] for d in rq["tests"].values() for x in d.values()))
    # Pre-registered split: conventions without DREsS (the only Score set).
    cc = rq["preregistered"]["conventions_choice"]
    m.add("cfAurocConvNoDress", num(cc["auroc_mean"]))
    m.add("cfTopErrConvNoDress", pct(cc["top_band_error_rate"], 1))
    m.add("cfConfErrConvNoDress", pct(cc["confident_error_share"], 0))
    md += ["", "### Per set", "",
           "Conf.: `field` = Jev's confidence field, `binary` = 2P(pred)−1. ECE = equal-mass ECE of the predicted option's "
           "probability [fixed CI] with its perfect-calibration floor (mean / 95th percentile of 1,000 label draws from the "
           "model's own probabilities; † = above the band, BH-significant); ECE(w) = equal-width ECE (sensitivity); — where the "
           "prediction aggregates several answers. Band cells under 20 units: --.", "",
           "| Set | Paper | Outcome | Cause | Conf. | Units | Acc. | AUROC [CI] | ECE [CI] (floor / band) | ECE(w) | Brier | AUGRC | E-AURC | err by band [0,.25) / [.25,.5) / [.5,.75) / [.75,1] (n top) | errors in top band |",
           "|---|---|---|---|---|---:|---:|---|---|---:|---:|---:|---:|---|---:|"]
    order = {k: i for i, (k, *_) in enumerate(CAUSES)}
    for k, v in sorted(sets.items(), key=lambda kv: (order[kv[1]["cause"]], -kv[1]["auroc"] if not bad(kv[1]["auroc"]) else 0)):
        bands = " / ".join(pct(b_["error_rate"], 0) for b_ in v["bands"])
        if v["has_probability"]:
            f = v["ece_floor"]
            ece = f"{num(v['ece'], 3)} {ci_s(v['ece_ci'], 3)} ({num(f['floor_mean'], 3)} / {num(f['floor_p95'], 3)}){' †' if v['bh_miscalibrated'] else ''}"
        else:
            ece = "—"
        md.append(f"| {v['name']} | {v['paper'].split('-')[0]} | {v['outcome']} | {v['cause']} | {v['confidence_kind'].split()[0]} | {v['n_units']:,} | "
                  f"{pct(v['accuracy'])} | {num(v['auroc'])} {ci_s(v['auroc_ci'])}{' *' if v['bh_auroc_gt_half'] else ''} | {ece} | "
                  f"{num(v['ece_equal_width'], 3) if v['has_probability'] else '—'} | {num(v['brier'], 3) if v['has_brier'] else '—'} | "
                  f"{num(v['augrc'], 3)} | {num(v['eaurc'], 3)} | {bands} ({v['bands'][3]['n']:,}) | {pct(v['confident_error_share'], 0)} |")
    md += ["", "\\* AUROC > 0.5 after BH. DREsS (ordinal): RPS " + num(sets["dress_new"]["rps"], 3) + " against "
           + num(sets["dress_new"]["rps_climatology"], 3) + " for the train-split level frequencies (RPS skill "
           + num(sets["dress_new"]["rps_skill"], 2) + ").", ""]
    m.add("cfDressRps", num(sets["dress_new"]["rps"], 3))
    m.add("cfDressRpsClim", num(sets["dress_new"]["rps_climatology"], 3))
    m.add("cfDressRpsSkill", tex_signed(sets["dress_new"]["rps_skill"], 2))
    convs = {k: v for k, v in sets.items() if v["cause"] == "conventions"}
    m.add("cfConvAurocMin", num(min(v["auroc"] for v in convs.values())))
    m.add("cfConvAurocMax", num(max(v["auroc"] for v in convs.values())))
    m.add("cfAllAurocMin", num(min(v["auroc"] for v in sets.values())))
    m.add("cfAllAurocMax", num(max(v["auroc"] for v in sets.values())))
    floors = [v["ece_floor"]["floor_mean"] for v in sets.values() if v["has_probability"]]
    m.add("cfEceFloorMin", num(min(floors), 3))
    m.add("cfEceFloorMax", num(max(floors), 3))


def rq1(m: Macros, md: list[str]) -> None:
    sets, rq = RES["sets"], RES["rq1"]
    comp = rq["comparable"]
    md += ["## RQ1: selective prediction (risk-coverage)", "",
           "Units are ranked by confidence and kept at or above a threshold. Comparable to the paper's number "
           f"({len(comp)} sets): primary metric accuracy (XSTest, SciPrompt, INLI), P@1 (TTP) or the paper reports the method's "
           "accuracy (PiNose). **Primary: Learn-then-Test** (δ = 0.05): on a random half of the clusters, thresholds are "
           "accepted in descending order while the one-sided Clopper–Pearson lower bound of the kept accuracy reaches the "
           "paper's number; the lowest accepted one is applied to the other half; swapped and pooled; 50 halvings. Reported: "
           "mean coverage, mean kept accuracy, share of halvings whose pooled kept accuracy reaches the number. INLI also "
           "dev-fitted (the same question's saved val run). Sensitivity (appendix): the naive cross-fitted threshold and the "
           "oracle c\\* (chosen on the test units it is scored on).", "",
           "| Set | Outcome | Basis | Paper | Jev acc. (100%) | LTT coverage / kept acc. | LTT halvings reaching | dev-fitted LTT | naive coverage / kept / reaching | oracle c* [CI] |",
           "|---|---|---|---:|---:|---|---:|---|---|---|"]
    for k in sorted(comp, key=lambda k: (-sets[k]["ltt"]["share_reaching"], -sets[k]["ltt"]["mean_coverage"])):
        v = sets[k]
        x, nv = v["ltt"], v["naive_cross_fitted"]
        dv = v.get("dev_fitted")
        dev = (f"{pct(dv['ltt']['coverage'], 0)}% / {pct(dv['ltt']['kept_accuracy'])}{' ✓' if dv['ltt']['reaches'] else ' ✗'}") if dv else "—"
        md.append(f"| {v['name']} | {v['outcome']} | {v['rq1_basis']} | {pct(v['target_accuracy'])} | {pct(v['acc_cov100'])} | "
                  f"{pct(x['mean_coverage'], 0)}% / {pct(x['mean_kept_accuracy'])} | {pct(x['share_reaching'], 0)}% | {dev} | "
                  f"{pct(nv['mean_coverage'], 0)}% / {pct(nv['mean_kept_accuracy'])} / {pct(nv['share_reaching'], 0)}% | "
                  f"{num(v['max_coverage_at_target'])} {ci_s(v['max_coverage_ci'])} |")
    names = lambda ks: ", ".join(sets[k]["name"] for k in ks) or "none"  # noqa: E731
    m.add("cfSelNComparable", len(comp))
    m.add("cfSelLttNMajority", len(rq["ltt_reach_majority"]))
    m.add("cfSelLttNNever", len(rq["ltt_reach_never"]))
    m.add("cfSelXfNMajority", len(rq["naive_reach_majority"]))
    m.add("cfSelXfNNever", sum(sets[k]["naive_cross_fitted"]["share_reaching"] == 0 for k in comp))
    m.add("cfSelNFull", len(rq["oracle_reach_full"]))
    m.add("cfSelHalvings", RES["halvings"])
    # results.tex names the sets below the paper on all items and those that reach it above the threshold, and
    # counts the first as cfSelNComparable - cfSelNFull.
    below = sorted(set(comp) - set(rq["oracle_reach_full"]))
    if below != ["inli", "pinose/webq", "sciprompt/s2orc", "ttp/expert", "ttp/procedures_plus", "ttp/tram"]:
        raise ValueError(f"sets below the paper on all items changed: {below}")
    if sorted(set(rq["ltt_reach_majority"]) & set(below)) != ["inli", "pinose/webq", "sciprompt/s2orc"]:
        raise ValueError(f"sets reaching the paper above the threshold changed: {rq['ltt_reach_majority']}")
    m.add("cfSelNPartial", len(rq["oracle_reach_partial"]))
    m.add("cfSelNNever", len(rq["oracle_never"]))
    m.add("cfSelGainFifty", pct(rq["median_gain_cov50"]))
    m.add("cfSelGainEighty", pct(rq["median_gain_cov80"]))
